import { ReportDocument } from '@shared/report-output/report-document.model';
import { ReportSection } from '@shared/report-output/report-section.model';
import { EmissionFactorsReportSnapshot } from '@app/v1/reports/shared/emission-factors/emission-factors-report-snapshot';
import { emissionFactorsTableView } from '@app/v1/reports/shared/emission-factors/emission-factors-table.view';

/** The shared writer's Helvetica font uses plain chemical labels instead of Unicode subscripts. */
function pdfText(value: string): string {
  return value.replace(/[₀-₉]/g, digit => String(digit.charCodeAt(0) - 0x2080)).replace(/[–—−]/g, '-');
}

export function emissionFactorsPdfDocument(snapshot: EmissionFactorsReportSnapshot): ReportDocument {
  const view = emissionFactorsTableView(snapshot.results), sections: ReportSection[] = [];
  sections.push({ type: 'styledText', content: [
    { text: pdfText(snapshot.name), fontSize: 18, bold: true, align: 'center' },
    { text: 'Generated by VERIFI', fontSize: 10, align: 'center' },
    { text: `${pdfText(view.facility.name)} | ${snapshot.startYear}-${snapshot.endYear}`, fontSize: 10, align: 'center' }
  ] });
  if (view.electricity.length) {
    sections.push({ type: 'heading', title: 'Electricity Emission Factors', tocInclude: true, tocLabel: 'Electricity Emission Factors', bookmarkLevel: 0 },
      { type: 'text', content: `Zip Code: ${view.facility.zip ?? ''} | eGRID Region: ${view.facility.eGridSubregion ?? ''}\nElectricity Meters: ${pdfText(view.electricityMeterNames)}` },
      { type: 'table', headers: [{ content: 'Year', rowSpan: 2 }, { content: 'Market Emission Rates', colSpan: 3 }, { content: 'Location Emission Rates', colSpan: 3 }],
        subHeaders: ['CO2 (kg CO2/MWh)', 'CH4 (g CH4/MWh)', 'N2O (g N2O/MWh)', 'CO2 (kg CO2/MWh)', 'CH4 (g CH4/MWh)', 'N2O (g N2O/MWh)'],
        rows: view.electricity.map(row => [String(row.year), ...row.marketValues.map(pdfText), ...row.locationValues.map(pdfText)]) });
  }
  if (view.other.length) {
    sections.push({ type: 'heading', title: 'Other Emission Factors', pageBreakBefore: !!view.electricity.length,
      tocInclude: true, tocLabel: 'Other Emission Factors', bookmarkLevel: 0 },
    { type: 'table', headers: ['Meter', 'Source', 'Fuel Type', 'CO2 Factor', 'CH4 Factor', 'N2O Factor'],
      rows: view.other.map(row => [pdfText(row.meterName + (row.unavailable ? `\n${row.unavailable}` : '')),
        row.source, pdfText(row.fuel), pdfText(row.co2), pdfText(row.ch4), pdfText(row.n2o)]) });
  }
  return { metadata: { title: pdfText(snapshot.name), subtitle: 'Generated by VERIFI', facilityName: pdfText(view.facility.name),
    dateGenerated: new Date().toISOString(), skipPage: true, moduleColor: [64, 94, 112] }, sections };
}
