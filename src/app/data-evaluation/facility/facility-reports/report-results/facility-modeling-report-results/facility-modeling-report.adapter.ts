import { AccountWorkspaceQueryService } from 'src/app/account-workspace/account-workspace-query.service';
import { AccountWorkspaceStore } from 'src/app/account-workspace/account-workspace.store';
import { inject, Injectable } from '@angular/core';
import { IdbFacilityReport, ModelingReportSettings } from "src/app/models/idbModels/facilityReport";
import { ReportDocument, ReportMetaData } from "src/app/shared/pdf-report/models/report-document.model";
import { BaseSection, TableSection, TextSection } from "src/app/shared/pdf-report/models/report-section.model";
import { IdbAnalysisItem } from "src/app/models/idbModels/analysisItem";
import { RegressionNumberPipe } from "src/app/shared/helper-pipes/regression-number.pipe";
import { UtilityMeterGroupdbService } from "src/app/indexedDB/utilityMeterGroup-db.service";
import { FacilityGroupAnalysisItem } from "src/app/shared/shared-analysis/calculations/regression-models.service";
import { FacilitydbService } from "src/app/indexedDB/facility-db.service";
import { UserDefineModelDateRangePipe } from "src/app/shared/shared-analysis/data-check/regression-model-details-table/user-define-model-date-range.pipe";
import { CustomNumberPipe } from "src/app/shared/helper-pipes/custom-number.pipe";

@Injectable({ providedIn: 'root' })
export class FacilityModelingReportAdapter {
  private readonly accountWorkspaceQuery = inject(AccountWorkspaceQueryService);
  private readonly accountWorkspaceStore = inject(AccountWorkspaceStore);

    private facilityDbService = inject(FacilitydbService);
    private regressionNumberPipe = inject(RegressionNumberPipe);
    private utilityMeterGroupDbService = inject(UtilityMeterGroupdbService);
    private userDefineModelDateRangePipe = inject(UserDefineModelDateRangePipe);
    private customNumberPipe = inject(CustomNumberPipe);

    report: IdbFacilityReport;
    reportSettings: ModelingReportSettings;
    analysisItem: IdbAnalysisItem;
    regressionGroupItems: Array<FacilityGroupAnalysisItem> = [];
    criticalItems: Array<FacilityGroupAnalysisItem> = [];
    moderateItems: Array<FacilityGroupAnalysisItem> = [];
    minorItems: Array<FacilityGroupAnalysisItem> = [];
    classicIntensityGroupItems: Array<FacilityGroupAnalysisItem> = [];
    absoluteGroupItems: Array<FacilityGroupAnalysisItem> = [];

    buildDocument(input: FacilityModelingReportData): ReportDocument {
        const sections: BaseSection[] = [];
        this.report = input.facilityReport;
        this.reportSettings = this.report.modelingReportSettings;
        this.analysisItem = input.analysisItem;
        this.regressionGroupItems = input.executiveSummaryItems.filter(item => {
            return item.group.analysisType == 'regression';
        });
        this.criticalItems = this.regressionGroupItems.filter(item => {
            return (item.group.analysisType == 'regression' && !item.selectedModel.isValid);
        });
        this.moderateItems = this.regressionGroupItems.filter(item => {
            return (item.group.analysisType == 'regression' && !item.selectedModel.SEPValidationPass && item.selectedModel.dataValidationNotes && item.selectedModel.dataValidationNotes.length > 0);
        });
        this.minorItems = this.regressionGroupItems.filter(item => {
            return (item.group.analysisType == 'regression' && item.selectedModel.modelNotes && item.selectedModel.modelNotes.length > 0);
        });
        this.classicIntensityGroupItems = input.executiveSummaryItems.filter(item => {
            return item.group.analysisType == 'energyIntensity';
        });
        this.absoluteGroupItems = input.executiveSummaryItems.filter(item => {
            return item.group.analysisType == 'absoluteEnergyConsumption';
        });

        let metadata: ReportMetaData = {
            title: `${this.report.name}`,
            subtitle: 'GENERATED BY VERIFI',
            dateGenerated: new Date().toISOString(),
            moduleColor: [46, 81, 127]
        };

        if (this.reportSettings.includeIssuesSummary && this.regressionGroupItems.length > 0) {
            sections.push(...this.buildIssuesSummarySection('Issues Summary', this.criticalItems, this.moderateItems, this.minorItems));
        }
        if (this.reportSettings.includeExecutiveSummary) {
            sections.push(...this.buildExecutiveSummarySection('Executive Summary', this.regressionGroupItems, this.classicIntensityGroupItems, this.absoluteGroupItems));
        }
        if (this.reportSettings.includeDataValidationTables && this.regressionGroupItems.length > 0) {
            sections.push(...this.buildDataValidationTablesSection('Data Validation Tables', this.regressionGroupItems));
        }

        return {
            metadata,
            sections
        };
    }

    buildIssuesSummarySection(title: string, criticalItems: Array<FacilityGroupAnalysisItem>, moderateItems: Array<FacilityGroupAnalysisItem>, minorItems: Array<FacilityGroupAnalysisItem>): BaseSection[] {
        let sections: BaseSection[] = [];
        sections.push({
            type: 'heading',
            title: title,
            tocInclude: true,
            tocLabel: title,
            bookmarkLevel: 0
        });

        if (criticalItems.length > 0) {
            const criticalSection = this.buildIssuesSummaryTableSection(['Facility', 'Group', 'Model Validation Failures'], 'Critical Issues', criticalItems);
            if (criticalSection) {
                criticalSection.tocInclude = true;
                criticalSection.tocLabel = 'Critical Issues';
                criticalSection.bookmarkLevel = 1;
                sections.push(criticalSection);
            }
        }
        if (moderateItems.length > 0) {
            const moderateSection = this.buildIssuesSummaryTableSection(['Facility', 'Group', 'Data Validation Failures'], 'Moderate Issues', moderateItems);
            if (moderateSection) {
                moderateSection.tocInclude = true;
                moderateSection.tocLabel = 'Moderate Issues';
                moderateSection.bookmarkLevel = 1;
                sections.push(moderateSection);
            }
        }
        if (minorItems.length > 0) {
            const minorSection = this.buildIssuesSummaryTableSection(['Facility', 'Group', 'Model Notes'], 'Minor Issues', minorItems);
            if (minorSection) {
                minorSection.tocInclude = true;
                minorSection.tocLabel = 'Minor Issues';
                minorSection.bookmarkLevel = 1;
                sections.push(minorSection);
            }
        }

        if (criticalItems.length === 0 && moderateItems.length === 0 && minorItems.length === 0) {
            const noIssuesSection: TextSection = {
                type: 'text',
                content: 'No Issues Identified',
            };
            sections.push(noIssuesSection);
        }

        const lastIndex = sections.length - 1;
        if (lastIndex >= 0) {
            sections[lastIndex].pageBreakAfter = true;
        }
        return sections;
    }

    buildExecutiveSummarySection(title: string, regressionGroupItems: Array<FacilityGroupAnalysisItem>, classicIntensityGroupItems: Array<FacilityGroupAnalysisItem>, absoluteGroupItems: Array<FacilityGroupAnalysisItem>): BaseSection[] {
        let sections: BaseSection[] = [];
        sections.push({
            type: 'heading',
            title: title,
            tocInclude: true,
            tocLabel: title,
            bookmarkLevel: 0
        });

        if (regressionGroupItems.length > 0) {
            const regressionSummarySection = this.buildRegressionSection('Analysis Type: Regression', regressionGroupItems);
            if (regressionSummarySection) {
                regressionSummarySection.tocInclude = true;
                regressionSummarySection.tocLabel = 'Analysis Type: Regression';
                regressionSummarySection.bookmarkLevel = 1;
                regressionSummarySection.pageBreakAfter = true;
                sections.push(regressionSummarySection);
            }
        }
        if (classicIntensityGroupItems.length > 0) {
            const classicIntensitySummarySection = this.buildClassicIntensitySection('Analysis Type: Classic Intensity', classicIntensityGroupItems);
            if (classicIntensitySummarySection) {
                classicIntensitySummarySection.tocInclude = true;
                classicIntensitySummarySection.tocLabel = 'Analysis Type: Classic Intensity';
                classicIntensitySummarySection.bookmarkLevel = 1;
                classicIntensitySummarySection.pageBreakAfter = true;
                sections.push(classicIntensitySummarySection);
            }
        }
        if (absoluteGroupItems.length > 0) {
            const absoluteSummarySection = this.buildAbsoluteSection('Analysis Type: Absolute', absoluteGroupItems);
            if (absoluteSummarySection) {
                absoluteSummarySection.tocInclude = true;
                absoluteSummarySection.tocLabel = 'Analysis Type: Absolute';
                absoluteSummarySection.bookmarkLevel = 1;
                absoluteSummarySection.pageBreakAfter = true;
                sections.push(absoluteSummarySection);
            }
        }
        return sections;
    }

    buildDataValidationTablesSection(title: string, regressionGroupItems: Array<FacilityGroupAnalysisItem>): BaseSection[] {
        let sections: BaseSection[] = [];
        sections.push({
            type: 'heading',
            title: title,
            tocInclude: true,
            tocLabel: title,
            bookmarkLevel: 0
        });

        if (regressionGroupItems.length > 0) {
            regressionGroupItems.forEach(item => {
                const regressionSummarySection = this.buildRegressionSection('', [item]);
                if (regressionSummarySection) {
                    regressionSummarySection.tocInclude = true;
                    regressionSummarySection.tocLabel = (this.accountWorkspaceStore.facilities().find(facility => facility.guid === (item.facilityId))?.name ?? '') + ' - ' + this.accountWorkspaceQuery.getMeterGroupName(item.group.idbGroupId);
                    regressionSummarySection.bookmarkLevel = 1;
                    sections.push(regressionSummarySection);
                }

                const modelValidationSection = this.buildModelValidationSection(item);
                if (modelValidationSection) {
                    modelValidationSection.pageBreakAfter = true;
                    sections.push(modelValidationSection);
                }
            });
        }
        return sections;
    }

    buildIssuesSummaryTableSection(headers: Array<string>, title: string, items: Array<FacilityGroupAnalysisItem>): TableSection | undefined {
        let rows: string[][] = [];

        items.forEach(item => {
            const facilityName = (this.accountWorkspaceStore.facilities().find(facility => facility.guid === (item.facilityId))?.name ?? '');
            const groupName = this.accountWorkspaceQuery.getMeterGroupName(item.group.idbGroupId);
            let notes = '';
            if (title === 'Critical Issues') {
                notes = item.selectedModel.modelValidationNotes ? item.selectedModel.modelValidationNotes.join('\n') : '';
            }
            if (title === 'Moderate Issues') {
                notes = item.selectedModel.dataValidationNotes ? item.selectedModel.dataValidationNotes.join('\n') : '';
            }
            if (title === 'Minor Issues') {
                notes = item.selectedModel.modelNotes ? item.selectedModel.modelNotes.join('\n') : '';
            }

            rows.push([
                facilityName,
                groupName,
                notes
            ]);
        });

        const tableSection: TableSection = {
            type: 'table',
            title: title,
            headers: headers,
            rows: rows
        }

        return tableSection;
    }

    buildRegressionSection(title: string, items: Array<FacilityGroupAnalysisItem>): TableSection | undefined {
        let headers = ['Facility', 'Group', 'Model Year', 'Variable p-Values', 'R2', 'Adjusted R2', 'Model p-Value', 'Formula', 'Model Notes'];
        let rows: string[][] = [];

        items.forEach(item => {
            const facilityName = (this.accountWorkspaceStore.facilities().find(facility => facility.guid === (item.facilityId))?.name ?? '');
            let groupName = this.accountWorkspaceQuery.getMeterGroupName(item.group.idbGroupId);
            groupName = item.selectedModel?.isUserDefinedModel ? '* ' + groupName : groupName;

            let modelYear: string;
            if (item.selectedModel?.isUserDefinedModel) {
                modelYear = this.userDefineModelDateRangePipe.transform(item.group);
            }
            else {
                modelYear = item.group.regressionModelYear ? item.group.regressionModelYear.toString() : '';
            }

            let variablePValues: string = '';
            let r2: string = '';
            let adjustedR2: string = '';
            let modelPValue: string = '';
            if (!item.selectedModel?.isUserDefinedModel && !item.selectedModel?.errorModeling) {
                item.selectedModel?.t.p?.forEach((pValue, index) => {
                    if (index === 0) {
                        return;
                    }
                    const predictor = item.selectedModel?.predictorVariables[index - 1];
                    if (!predictor) {
                        return;
                    }
                    const pVal = pValue.toFixed(2);
                    variablePValues += `${predictor.name}: ${pVal}\n `;
                });
                variablePValues = variablePValues.slice(0, -2);

                r2 = item.selectedModel?.R2 ? item.selectedModel.R2.toFixed(3) : '';
                adjustedR2 = item.selectedModel?.adjust_R2 ? item.selectedModel.adjust_R2.toFixed(3) : '';
                modelPValue = item.selectedModel?.modelPValue ? item.selectedModel.modelPValue.toFixed(2) : '';
            }
            else {
                variablePValues = '\u2014';
                r2 = '\u2014';
                adjustedR2 = '\u2014';
                modelPValue = '\u2014';
            }

            let formula: string = '';
            item.selectedModel.coef?.forEach((coef, index) => {
                if (index === 0) {
                    formula += this.regressionNumberPipe.transform(coef);
                }
                if (index !== 0) {
                    const val = this.regressionNumberPipe.transform(coef);
                    formula += ` + (${val}*${item.selectedModel.predictorVariables[index - 1].name})`;
                }
            });
            let modelNotes: string = '';
            if (item.selectedModel?.modelNotes && item.selectedModel.modelNotes.length > 0) {
                item.selectedModel.modelNotes.forEach(note => {
                    modelNotes += `${note}\n`;
                });
            }
            if (item.selectedModel?.modelNotes && item.selectedModel.modelNotes.length == 0) {
                modelNotes = '\u2014';
            }


            rows.push([
                facilityName,
                groupName,
                modelYear,
                variablePValues,
                r2,
                adjustedR2,
                modelPValue,
                formula,
                modelNotes
            ]);
        });

        const tableSection: TableSection = {
            type: 'table',
            title: title,
            headers: headers,
            rows: rows
        }
        return tableSection;
    }

    buildClassicIntensitySection(title: string, classicIntensityGroupItems: Array<FacilityGroupAnalysisItem>): TableSection | undefined {
        let headers = ['Facility', 'Group', 'Baseline Year', 'Predictor Variables']
        let rows: string[][] = [];

        classicIntensityGroupItems.forEach(item => {
            const facilityName = (this.accountWorkspaceStore.facilities().find(facility => facility.guid === (item.facilityId))?.name ?? '');
            let groupName = this.accountWorkspaceQuery.getMeterGroupName(item.group.idbGroupId);
            let predictorVariables: string = '';
            item.group.predictorVariables.forEach(p => {
               if (p.productionInAnalysis) {
                   predictorVariables += `${p.name}\n`;
               }
            });
            rows.push([
                facilityName,
                groupName,
                item.baselineYear ? item.baselineYear.toString() : '',
                predictorVariables
            ]);
        });

        const tableSection: TableSection = {
            type: 'table',
            title: title,
            headers: headers,
            rows: rows
        }
        return tableSection;
    }

    buildAbsoluteSection(title: string, absoluteGroupItems: Array<FacilityGroupAnalysisItem>): TableSection | undefined {
        let headers = ['Facility', 'Group', 'Baseline Year']
        let rows: string[][] = [];

        absoluteGroupItems.forEach(item => {
            const facilityName = (this.accountWorkspaceStore.facilities().find(facility => facility.guid === (item.facilityId))?.name ?? '');
            let groupName = this.accountWorkspaceQuery.getMeterGroupName(item.group.idbGroupId);
            rows.push([
                facilityName,
                groupName,
                item.baselineYear ? item.baselineYear.toString() : ''
            ]);
        });

        const tableSection: TableSection = {
            type: 'table',
            title: title,
            headers: headers,
            rows: rows
        }
        return tableSection;
    }

    buildModelValidationSection(item: FacilityGroupAnalysisItem): TableSection | undefined {
        const headers = ['', ''];
        const rows: string[][] = [];

        item.selectedModel.SEPValidation?.forEach(validationItem => {
            headers.push(validationItem.predictorVariable);
        });

        rows.push([
            '',
            'Mean Report Year Value',
            ...item.selectedModel.SEPValidation.map(validationItem => this.checkNumber(validationItem.meanReportYear))
        ]);

        rows.push([
            '',
            'Mean Baseline Year Value',
            ...item.selectedModel.SEPValidation.map(validationItem => this.checkNumber(validationItem.meanBaselineYear))
        ]);

        rows.push([
            'Range 1',
            'Minimum of Model Variable',
            ...item.selectedModel.SEPValidation.map(validationItem => this.checkNumber(validationItem.modelMin))
        ]);

        rows.push([
            '',
            'Maximum of Model Variable',
            ...item.selectedModel.SEPValidation.map(validationItem => this.checkNumber(validationItem.modelMax))
        ]);

        rows.push([
            'Range 2',
            'Model Mean - 3 Std Dev',
            ...item.selectedModel.SEPValidation.map(validationItem => this.checkNumber(validationItem.modelMinus3StdDev))
        ]);

        rows.push([
            '',
            'Model Mean + 3 Std Dev',
            ...item.selectedModel.SEPValidation.map(validationItem => this.checkNumber(validationItem.modelPlus3StdDev))
        ]);

        rows.push([
            '',
            'Validation Check',
            ...item.selectedModel.SEPValidation.map(validationItem => validationItem.isValid ? 'Pass' : 'Fail')
        ]);

        const tableSection: TableSection = {
            type: 'table',
            title: '',
            headers: headers,
            rows: rows
        }
        return tableSection;
    }

    checkNumber(value: number): string {
        if (value === null || value === undefined || isNaN(value) || value === 0) {
            return '\u2014';
        }
        return this.customNumberPipe.transform(value);
    }
}

export interface FacilityModelingReportData {
    facilityReport: IdbFacilityReport;
    analysisItem: IdbAnalysisItem;
    executiveSummaryItems: Array<FacilityGroupAnalysisItem>;
}