import { PptDocument } from '@shared/report-output/ppt-document';
import { ImageSlide, PptSlide } from '@shared/report-output/ppt-slide';
import { MODELING_REGRESSION_HEADERS, MODELING_DETAILS_HEADERS } from '../modeling-report-tables';
import { ModelingOutputChart, ModelingReportExportSnapshot, modelingReportSections } from './modeling-report-output';

export function modelingPptDocument(snapshot: ModelingReportExportSnapshot,
  chartProvider?: (chart: ModelingOutputChart) => ImageSlide['imageDataProvider']): PptDocument {
  const date = new Date().toISOString(), subtitle = `${snapshot.scopeName}\nGenerated by VERIFI`;
  const slides: PptSlide[] = [{ type: 'title', title: snapshot.name, subtitle, date }];
  let sectionTitle = '', groupTitle = '';
  for (const section of modelingReportSections(snapshot.view)) {
    if (section.type === 'heading') {
      sectionTitle = section.title!; groupTitle = '';
      slides.push({ type: 'title', title: sectionTitle, layout: 'section' });
    } else if (section.type === 'styledText') {
      if (section.bookmarkLevel === 1) groupTitle = section.content[0].text;
      else slides.push({ type: 'table', title: groupTitle || sectionTitle,
        headers: ['Report note'], rows: [[section.content.map(line => line.text).join('\n')]] });
    } else if (section.type === 'table') {
      const regression = [MODELING_REGRESSION_HEADERS, MODELING_DETAILS_HEADERS].some(headers => section.headers.length === headers.length
        && section.headers.every((header, index) => header === headers[index]));
      slides.push({ type: 'table', title: section.title || groupTitle || sectionTitle,
        // The shared writer repeats column zero on every band. Keep both identifiers there.
        headers: regression ? ['Facility / Group', ...section.headers.slice(2)] : [...section.headers],
        rows: regression ? section.rows.map(row => [`${row[0]} · ${row[1]}`, ...row.slice(2)]) : section.rows.map(row => [...row]),
        equation: section.equation,
        columnWidths: regression ? (section.equation ? [2.2, 1.2, 2, .7, .9, 1.1, 4] : [2.2, 1.2, 2, .7, .9, 1.1, 4, 4])
          : section.equation ? [1.7, 2, .7, .9, 1.1, 4] : undefined
      });
    } else if (section.type === 'chart') {
      slides.push({ type: 'image', title: section.title || groupTitle,
        imageDataProvider: chartProvider?.(section), imageWidth: 1200, imageHeight: 675 });
    }
  }
  return { metadata: { title: snapshot.name, subtitle, date }, slides };
}
