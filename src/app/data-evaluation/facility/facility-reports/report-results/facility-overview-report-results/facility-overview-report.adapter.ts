import { AccountWorkspaceQueryService } from 'src/app/account-workspace/account-workspace-query.service';
import { inject, Injectable } from '@angular/core';
import { DataOverviewFacilityReportSettings, IdbFacilityReport } from "src/app/models/idbModels/facilityReport";
import { ReportDocument, ReportMetaData } from "src/app/shared/pdf-report/models/report-document.model";
import { BaseSection, ChartSection, HeadingSection, TableHeaderCell, TableSection } from "src/app/shared/pdf-report/models/report-section.model";
import { CustomNumberPipe } from "src/app/shared/helper-pipes/custom-number.pipe";
import { IdbFacility } from "src/app/models/idbModels/facility";
import { FacilityOverviewData, FacilityOverviewMeter } from "src/app/calculations/dashboard-calculations/facilityOverviewClass";
import { UtilityUseAndCost } from "src/app/calculations/dashboard-calculations/useAndCostClass";
import { formatDate } from "@angular/common";
import { EnergySources, WaterSources } from "src/app/models/constantsAndTypes";

@Injectable({ providedIn: 'root' })
export class FacilityOverviewReportAdapter {
  private readonly accountWorkspaceQuery = inject(AccountWorkspaceQueryService);

    private customNumberPipe: CustomNumberPipe = inject(CustomNumberPipe);

    report: IdbFacilityReport;
    reportSettings: DataOverviewFacilityReportSettings;
    facility: IdbFacility;
    facilityOverviewData: FacilityOverviewData;
    energyUnit: string;
    waterUnit: string;
    utilityUseAndCost: UtilityUseAndCost;
    dateRange: {
        startDate: Date,
        endDate: Date
    };
    previousYear: Date;

    buildDocument(input: FacilityOverviewReportData): ReportDocument {
        const sections: BaseSection[] = [];
        this.report = input.facilityReport;
        this.reportSettings = this.report.dataOverviewReportSettings;
        this.facility = input.facility;
        this.facilityOverviewData = input.facilityOverviewData;
        this.energyUnit = this.facility.energyUnit;
        this.waterUnit = this.facility.volumeLiquidUnit;
        this.utilityUseAndCost = input.utilityUseAndCost;
        this.dateRange = input.dateRange;
        this.previousYear = this.utilityUseAndCost.previousYear;

        let metadata: ReportMetaData = {
            title: `${this.report.name}`,
            subtitle: 'GENERATED BY VERIFI',
            dateGenerated: new Date().toISOString(),
            moduleColor: [46, 81, 127]
        };

        if (this.reportSettings.includeEnergySection) {
            sections.push(...this.buildSection(input.chartImageProviders, 'Energy Consumption', 'energyUse', 'Utility Usage'));
        }
        if (this.reportSettings.includeWaterSection) {
            sections.push(...this.buildSection(input.chartImageProviders, 'Water', 'water', 'Water Usage'));
        }
        if (this.reportSettings.includeCostsSection) {
            sections.push(...this.buildSection(input.chartImageProviders, 'Costs', 'cost', 'Utility Costs'));
        }

        return {
            metadata,
            sections
        };
    }

    private buildSection(chartImageProviders: any, title: string, dataType: 'energyUse' | 'cost' | 'water', tocLabel: string): BaseSection[] {
        let sections: BaseSection[] = [];

        if (this.reportSettings.includeMeterUsageStackedLineChart && this.hasMeterData(dataType)) {
            let chartSection = this.createChartSection(chartImageProviders?.meterStackedLineChart?.[dataType], '');
            if (chartSection) {
                chartSection.tocInclude = true;
                chartSection.tocLabel = tocLabel;
                chartSection.bookmarkLevel = 1;
                chartSection.pageBreakAfter = true;
                sections.push(chartSection);
            }
        }

        if (this.reportSettings.includeMeterUsageTable && this.hasMeterData(dataType)) {
            let tableSection = this.createMeterUsageTableSection(dataType, `${tocLabel} Breakdown`);
            if (tableSection) {
                tableSection.tocInclude = true;
                tableSection.tocLabel = `${tocLabel} Breakdown Table`;
                tableSection.bookmarkLevel = 1;
                tableSection.pageBreakAfter = true;
                sections.push(tableSection);
            }
        }

        if (this.reportSettings.includeMeterUsageDonut && this.hasMeterData(dataType)) {
            let chartSection = this.createChartSection(chartImageProviders?.meterBarChart?.[dataType], `${tocLabel} Breakdown`);
            if (chartSection) {
                chartSection.tocInclude = true;
                chartSection.tocLabel = `${tocLabel} Breakdown Chart`;
                chartSection.bookmarkLevel = 1;
                chartSection.pageBreakAfter = true;
                sections.push(chartSection);
            }
        }

        if (this.reportSettings.includeUtilityTableForFacility && this.hasUtilityData(dataType)) {
            let tableSection = this.createUtilityTableSection(dataType, `${tocLabel} Comparison`);
            if (tableSection) {
                tableSection.tocInclude = true;
                tableSection.tocLabel = `${tocLabel} Comparison Table`;
                tableSection.bookmarkLevel = 1;
                tableSection.pageBreakAfter = true;
                sections.push(tableSection);
            }
        }

        if (this.reportSettings.includeAnnualBarChart && this.hasAnnualSourceData(dataType)) {
            let chartSection = this.createChartSection(chartImageProviders?.annualBarChart?.[dataType], `Annual ${tocLabel}`);
            if (chartSection) {
                chartSection.tocInclude = true;
                chartSection.tocLabel = `Annual ${tocLabel}`,
                chartSection.bookmarkLevel = 1;
                chartSection.pageBreakAfter = true;
                sections.push(chartSection);
            }
        }

        if (this.reportSettings.includeMonthlyLineChartForFacility && this.hasYearMonthData(dataType)) {
            let chartSection = this.createChartSection(chartImageProviders?.monthlyUsageLineChart?.[dataType], `Monthly ${tocLabel}`);
            if (chartSection) {
                chartSection.tocInclude = true;
                chartSection.tocLabel = `Monthly ${tocLabel}`,
                chartSection.bookmarkLevel = 1;
                chartSection.pageBreakAfter = true;
                sections.push(chartSection);
            }
        }

        if (sections.length === 0) {
            return [];
        }

        let titleSection: HeadingSection = {
            type: 'heading',
            title: this.facility.name + ' ' + title,
            tocInclude: true,
            tocLabel: this.facility.name + ' ' + title,
            bookmarkLevel: 0,
        };
        return [titleSection, ...sections];
    }

    private createMeterUsageTableSection(dataType: 'energyUse' | 'cost' | 'water', title: string): TableSection {
        const meters: Array<FacilityOverviewMeter> = this.getMetersByDataType(dataType);

        let headers: Array<string> = ['Meter', 'Utility', 'Group'];
        if (dataType === 'energyUse') {
            headers.push('Utility Usage (' + this.energyUnit + ')');
        }
        if (dataType === 'water') {
            headers.push('Consumption (' + this.waterUnit + ')');
        }
        headers.push('Utility Cost');

        const rows: string[][] = meters?.map(overviewMeter => {
            const row: string[] = [
                overviewMeter.meter?.name || '-',
                overviewMeter.meter?.source || '-',
                this.accountWorkspaceQuery.getMeterGroupName(overviewMeter.meter?.groupId) || '-'
            ];
            if (dataType === 'energyUse' || dataType === 'water') {
                row.push(this.checkNumber(overviewMeter.totalUsage));
            }
            row.push(this.checkCurrency(overviewMeter.totalCost));
            return row;
        });

        const totalRow: string[] = ['Total', '', ''];
        if (dataType === 'energyUse') {
            totalRow.push(this.checkNumber(this.facilityOverviewData.totalEnergyUsage));
            totalRow.push(this.checkCurrency(this.facilityOverviewData.totalEnergyCost));
        }
        else if (dataType === 'water') {
            totalRow.push(this.checkNumber(this.facilityOverviewData.totalWaterConsumption));
            totalRow.push(this.checkCurrency(this.facilityOverviewData.totalWaterCost));
        }
        else if (dataType === 'cost') {
            totalRow.push(this.checkCurrency(this.facilityOverviewData.totalFacilityCost));
        }
        rows.push(totalRow);

        const tableSection: TableSection = {
            type: 'table',
            title: title,
            headers: headers,
            rows: rows
        };

        return tableSection;
    }

    createUtilityTableSection(dataType: 'energyUse' | 'cost' | 'water', title: string): TableSection {
        const { sources, total } = this.getUtilitySourcesAndTotals(dataType);

        let label: string;
        if (dataType === 'energyUse') {
            label = 'Utility Use (' + this.energyUnit + ')';
        }
        else {
            label = 'Utility Use (' + this.waterUnit + ')';
        }
        let headers: Array<string | TableHeaderCell> = [];
        let subHeaders: Array<string | TableHeaderCell> = [];
        const rows: string[][] = [];

        const endDate: string = '(' + this.formatDate(this.dateRange.endDate) + ')';
        const previousYear: string = '(' + this.formatDate(this.previousYear) + ')';
        const dateRange: string = '(' + this.formatDate(this.dateRange.startDate) + ' - ' + this.formatDate(this.dateRange.endDate) + ')';

        if (dataType === 'energyUse' || dataType === 'water') {
            headers = [
                { content: '', colSpan: 1 },
                { content: 'Latest Month ' + endDate, colSpan: 2 },
                { content: 'Previous Year ' + previousYear, colSpan: 2 },
                { content: 'Monthly Average ' + dateRange, colSpan: 2 }
            ];

            subHeaders = ['Utility', label, 'Utility Cost', label, 'Utility Cost', label, 'Utility Cost'];

            sources.forEach(source => {
                const row: string[] = [
                    source.source,
                    this.checkNumber(source.end?.energyUse),
                    this.checkCurrency(source.end?.cost),
                    this.checkNumber(source.previousYear?.energyUse),
                    this.checkCurrency(source.previousYear?.cost),
                    this.checkNumber(source.average?.energyUse),
                    this.checkCurrency(source.average?.cost)
                ];
                rows.push(row);
            });

            rows.push([
                'Total',
                this.checkNumber(total.end?.energyUse),
                this.checkCurrency(total.end?.cost),
                this.checkNumber(total.previousYear?.energyUse),
                this.checkCurrency(total.previousYear?.cost),
                this.checkNumber(total.average?.energyUse),
                this.checkCurrency(total.average?.cost)
            ]);
        }
        else if (dataType === 'cost') {
            headers = ['Utility', 'Latest Month ' + endDate, 'Previous Year ' + previousYear, 'Monthly Average ' + dateRange];
            sources.forEach(source => {
                const row: string[] = [
                    source.source,
                    this.checkCurrency(source.end?.cost),
                    this.checkCurrency(source.previousYear?.cost),
                    this.checkCurrency(source.average?.cost)
                ];
                rows.push(row);
            });

            rows.push([
                'Total',
                this.checkCurrency(total.end?.cost),
                this.checkCurrency(total.previousYear?.cost),
                this.checkCurrency(total.average?.cost)
            ]);
        }


        const tableSection: TableSection = {
            type: 'table',
            title: title,
            headers: headers,
            subHeaders: subHeaders.length ? subHeaders : undefined,
            rows: rows
        };
        return tableSection;
    }

    getMetersByDataType(dataType: 'energyUse' | 'cost' | 'water'): Array<FacilityOverviewMeter> {
        if (dataType === 'energyUse') {
            return this.facilityOverviewData.energyMeters || [];
        }
        if (dataType === 'cost') {
            return this.facilityOverviewData.costMeters || [];
        }
        if (dataType === 'water') {
            return this.facilityOverviewData.waterMeters || [];
        }
        return [];
    }

    getUtilitySourcesAndTotals(dataType: 'energyUse' | 'cost' | 'water') {
        if (dataType === 'energyUse') {
            return {
                sources: this.utilityUseAndCost.energyUseAndCost || [],
                total: this.utilityUseAndCost.energyTotal
            };
        }
        if (dataType === 'cost') {
            return {
                sources: this.utilityUseAndCost.allSourcesUseAndCost || [],
                total: this.utilityUseAndCost.allSourcesTotal
            };
        }
        if (dataType === 'water') {
            return {
                sources: this.utilityUseAndCost.waterUseAndCost || [],
                total: this.utilityUseAndCost.waterTotal
            };
        }
    }

    private createChartSection(chartImageProvider: any, title: string) {
        const chartSection: ChartSection = {
            type: 'chart',
            title: title,
            imageDataProvider: chartImageProvider ? chartImageProvider : undefined
        };
        return chartSection;
    }

    checkNumber(value: number): string {
        if (isNaN(value) || value === null || value === undefined || value === 0) {
            return '\u2014';
        }
        return this.customNumberPipe.transform(value);
    }

    checkCurrency(value: number): string {
        if (isNaN(value) || value === null || value === undefined || value === 0) {
            return '\u2014';
        }
        return this.customNumberPipe.transform(value, true);
    }

    formatDate(date: Date): string {
        if (!date) {
            return '-';
        }
        return formatDate(date, 'MMM, yyyy', 'en-US');
    }

    hasMeterData(dataType: 'energyUse' | 'cost' | 'water'): boolean {
        const meters = this.getMetersByDataType(dataType);
        return meters?.length > 0;
    }

    hasUtilityData(dataType: 'energyUse' | 'cost' | 'water'): boolean {
        const { sources } = this.getUtilitySourcesAndTotals(dataType);
        return sources?.length > 0;
    }

    hasAnnualSourceData(dataType: 'energyUse' | 'cost' | 'water'): boolean {
        const annualSourceData = this.facilityOverviewData?.annualSourceData || [];

        if (dataType === 'energyUse') {
            return annualSourceData.some(source =>
                EnergySources.includes(source.source) && (source.annualSourceDataItems?.length || 0) > 0
            );
        } else if (dataType === 'water') {
            return annualSourceData.some(source =>
                WaterSources.includes(source.source) && (source.annualSourceDataItems?.length || 0) > 0
            );
        }
        return annualSourceData.some(source => (source.annualSourceDataItems?.length || 0) > 0);
    }

    hasYearMonthData(dataType: 'energyUse' | 'cost' | 'water'): boolean {
        if (dataType === 'energyUse' && this.facilityOverviewData?.energyYearMonthData?.length > 0) {
            return true;
        }
        if (dataType === 'cost' && this.facilityOverviewData?.allSourcesYearMonthData?.length > 0) {
            return true;
        }
        if (dataType === 'water' && this.facilityOverviewData?.waterYearMonthData?.length > 0) {
            return true;
        }
        return false;
    }
}

export interface FacilityOverviewReportData {
    facilityReport: IdbFacilityReport;
    facility: IdbFacility;
    facilityOverviewData: FacilityOverviewData;
    utilityUseAndCost: UtilityUseAndCost;
    dateRange: {
        startDate: Date,
        endDate: Date
    };
    chartImageProviders?: {
        meterStackedLineChart?: Record<string, () => Promise<string>>;
        meterBarChart?: Record<string, () => Promise<string>>;
        annualBarChart?: Record<string, () => Promise<string>>;
        monthlyUsageLineChart?: Record<string, () => Promise<string>>;
    }
}