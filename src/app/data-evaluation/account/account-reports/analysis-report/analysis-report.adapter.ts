import { inject, Injectable } from "@angular/core";
import { IdbAccountReport } from "src/app/models/idbModels/accountReport";
import { ReportDocument, ReportMetaData } from "src/app/shared/pdf-report/models/report-document.model";
import { BaseSection } from "src/app/shared/pdf-report/models/report-section.model";
import { IdbAnalysisItem } from "src/app/models/idbModels/analysisItem";
import { FacilityGroupAnalysisItem } from "src/app/shared/shared-analysis/calculations/regression-models.service";
import { AnalysisReportSetup } from "src/app/models/overview-report";
import { FacilityModelingReportAdapter } from "src/app/data-evaluation/facility/facility-reports/report-results/facility-modeling-report-results/facility-modeling-report.adapter";

@Injectable({ providedIn: 'root' })
export class AnalysisReportAdapter {

    private facilityModelingReportAdapter = inject(FacilityModelingReportAdapter);

    report: IdbAccountReport;
    reportSettings: AnalysisReportSetup;
    facilityAnalysisItems: Array<IdbAnalysisItem> = [];

    buildDocument(input: AnalysisReportData): ReportDocument {
        const sections: BaseSection[] = [];
        this.report = input.accountReport;
        this.reportSettings = this.report.analysisReportSetup;
        
        const regressionGroupItems = input.executiveSummaryItems.filter(item => {
            return item.group.analysisType == 'regression';
        });
        const criticalItems = regressionGroupItems.filter(item => {
            return (item.group.analysisType == 'regression' && !item.selectedModel.isValid);
        });
        const moderateItems = regressionGroupItems.filter(item => {
            return (item.group.analysisType == 'regression' && !item.selectedModel.SEPValidationPass && item.selectedModel.dataValidationNotes && item.selectedModel.dataValidationNotes.length > 0);
        });
        const minorItems = regressionGroupItems.filter(item => {
            return (item.group.analysisType == 'regression' && item.selectedModel.modelNotes && item.selectedModel.modelNotes.length > 0);
        });
        const classicIntensityGroupItems = input.executiveSummaryItems.filter(item => {
            return item.group.analysisType == 'energyIntensity';
        });
        const absoluteGroupItems = input.executiveSummaryItems.filter(item => {
            return item.group.analysisType == 'absoluteEnergyConsumption';
        });

        let metadata: ReportMetaData = {
            title: `${this.report.name}`,
            subtitle: 'GENERATED BY VERIFI',
            dateGenerated: new Date().toISOString(),
            moduleColor: [46, 81, 127]
        };

        if (this.facilityAnalysisItems && this.reportSettings.includeProblemsInformation && regressionGroupItems.length > 0) {
            sections.push(...this.facilityModelingReportAdapter.buildIssuesSummarySection('Issues Summary', criticalItems, moderateItems, minorItems));
        }
        if (this.reportSettings.includeExecutiveSummary) {
            sections.push(...this.facilityModelingReportAdapter.buildExecutiveSummarySection('Executive Summary', regressionGroupItems, classicIntensityGroupItems, absoluteGroupItems));
        }
        if (this.reportSettings.includeDataValidationTables && regressionGroupItems.length > 0) {
            sections.push(...this.facilityModelingReportAdapter.buildDataValidationTablesSection('Data Validation Tables', regressionGroupItems));
        }

        return {
            metadata,
            sections
        };
    }
}

export interface AnalysisReportData {
    accountReport: IdbAccountReport;
    facilityAnalysisItems: Array<IdbAnalysisItem>;
    executiveSummaryItems: Array<FacilityGroupAnalysisItem>;
}