import { inject, Injectable } from "@angular/core";
import { ReportDocument, ReportMetaData } from "@v0/shared/pdf-report/models/report-document.model";
import { BaseSection, StyledTextSection, TableHeaderCell, TableSection } from "@v0/shared/pdf-report/models/report-section.model";
import { IdbAccount } from "@app/data/models/idbModels/account";
import { AccountWorkspaceStore } from "@app/data/account-workspace/account-workspace.store";
import { IdbFacility } from "@app/data/models/idbModels/facility";
import { IdbAccountReport } from "@app/data/models/idbModels/accountReport";
import { IdbCustomFuel } from "@app/data/models/idbModels/customFuel";
import { EmissionFactorsReportData } from "./account-emission-factors-report-table/account-emission-factors-report-table.component";
import { AccountWorkspaceQueryService } from "@app/data/account-workspace/account-workspace-query.service";
import { SubregionEmissions } from "@app/data/models/eGridEmissions";
import { getEmissionsRate, getFuelEmissionsOutputRate } from "@app/domain/calculations/emissions-calculations/emissions";
import { FuelTypeOption } from "@app/shared/fuel-options/fuelTypeOption";
import { getMobileFuelTypes } from "@app/shared/fuel-options/getFuelTypeOptions";
import { EmissionElectricity, EmissionOthers } from "@app/v0/data-evaluation/facility/facility-reports/report-results/facility-emission-factors-report-results/facility-emission-factors-report-results.component";
import { EGridService } from "@app/shared/helper-services/e-grid.service";
import { IdbUtilityMeter } from "@app/data/models/idbModels/utilityMeter";

@Injectable({ providedIn: 'root' })
export class AccountEmissionFactorsReportAdapter {

    private accountWorkspaceStore: AccountWorkspaceStore = inject(AccountWorkspaceStore);
    private accountWorkspaceQuery: AccountWorkspaceQueryService = inject(AccountWorkspaceQueryService);
    private eGridService: EGridService = inject(EGridService);
    report: IdbAccountReport;
    account: IdbAccount;
    accountFacilities: Array<IdbFacility> = [];
    customFuels: Array<IdbCustomFuel>;
    emissionData: Array<EmissionFactorsReportData> = [];

    buildDocument(input: EmissionFactorsInput): ReportDocument {
        const sections: BaseSection[] = [];
        this.report = input.report;
        this.accountFacilities = input.accountFacilities;
        this.account = this.accountWorkspaceStore.account();
        this.customFuels = [...this.accountWorkspaceStore.customFuels()];
        this.accountFacilities.forEach(facility => {
            let facilityMeters = this.accountWorkspaceQuery.getFacilityMeters(facility.guid);
            this.setReportData(facility, facilityMeters);
        });

        let metadata: ReportMetaData = {
            title: `${this.report.name}`,
            subtitle: 'GENERATED BY VERIFI',
            dateGenerated: new Date().toISOString(),
            moduleColor: [46, 81, 127]
        };

        if (this.emissionData?.length > 0) {
            this.emissionData.forEach(data => {
                let facilitySections: BaseSection[] = [];
                if (data.emissionsElectricity?.length > 0) {
                    facilitySections.push(...this.buildElectricitySections(data.emissionsElectricity, data.electricityMeters, data.facility));
                }
                if (data.otherEmissions?.length > 0) {
                    facilitySections.push(...this.buildOtherFuelsSections(data.otherEmissions));
                }
                if (facilitySections.length > 0) {
                    let titleSection = this.buildTitleSection(data.facility.name);
                    sections.push(titleSection, ...facilitySections);
                }
            });
        }

        return {
            metadata,
            sections
        };
    }

    setReportData(facility: IdbFacility, facilityMeters: IdbUtilityMeter[]) {
        let emissionDataElectricity: Array<EmissionElectricity> = [];
        let emissionData: Array<EmissionOthers> = [];
        let electricityMeters: Array<string> = [];

        let co2EmissionsRates: Array<SubregionEmissions> = this.eGridService.co2Emissions.map(rate => { return rate });

        facilityMeters.forEach(meter => {
            if (meter.source === 'Electricity') {
                electricityMeters.push(meter.name);
            }
            if (meter.source === 'Electricity' && emissionDataElectricity.length === 0) {
                for (let year = this.report.startYear; year <= this.report.endYear; year++) {
                    let emissionsRate = getEmissionsRate(facility.eGridSubregion, year, co2EmissionsRates);
                    if (emissionsRate) {
                        emissionDataElectricity.push({
                            source: meter.source,
                            year: year,
                            marketRate: emissionsRate.marketRate,
                            locationRate: emissionsRate.locationRate,
                            directEmissionsRate: emissionsRate.directEmissionsRate
                        });
                    }
                }
            }
            if (meter.source == 'Natural Gas' || (meter.source == 'Other Fuels' && meter.scope != 2) || meter.source == 'Other Energy') {
                let emissionsOutputRate = getFuelEmissionsOutputRate(meter.source, meter.fuel, meter.phase, this.customFuels, meter.scope, meter.vehicleCategory, meter.vehicleType);
                let selectedUnit;
                if (meter.source == 'Other Fuels') {
                    selectedUnit = meter.vehicleCollectionUnit;
                }
                else {
                    selectedUnit = meter.energyUnit;
                }
                emissionData.push({
                    meterName: meter.name,
                    source: meter.source,
                    fuelValue: meter.fuel ? meter.fuel : '',
                    CO2: emissionsOutputRate.CO2,
                    CH4: emissionsOutputRate.CH4,
                    N2O: emissionsOutputRate.N2O,
                    unit: selectedUnit
                });
            }

            if (meter.source == 'Other Fuels' && meter.scope == 2) {
                let fuelOptions: Array<FuelTypeOption> = getMobileFuelTypes(meter.vehicleCategory, meter.vehicleType, this.customFuels);
                let meterFuel: FuelTypeOption = fuelOptions.find(option => {
                    return option.value == meter.vehicleFuel
                });

                let selectedUnit;
                if (meterFuel.isOnRoad) {
                    selectedUnit = meter.vehicleDistanceUnit;
                } else {
                    selectedUnit = meter.vehicleCollectionUnit;
                }

                emissionData.push({
                    meterName: meter.name,
                    source: meter.source,
                    fuelValue: meterFuel.value,
                    CO2: meterFuel.CO2,
                    CH4: meterFuel.CH4,
                    N2O: meterFuel.N2O,
                    unit: selectedUnit
                });
            }
        });
        this.emissionData.push({
            facility: facility,
            emissionsElectricity: emissionDataElectricity,
            otherEmissions: emissionData,
            electricityMeters: electricityMeters
        });
    }

    buildTitleSection(title: string): StyledTextSection {
        return {
            type: 'styledText',
            content: [
                {
                    text: title,
                    fontSize: 16,
                    align: 'center',
                    bold: true
                }
            ],
            verticalCenter: true,
            pageBreakAfter: true,
            tocInclude: true,
            tocLabel: title,
            bookmarkLevel: 0
        };
    }

    buildElectricitySections(emissionDataElectricity: Array<EmissionElectricity>, electricityMeters: string[], facility: IdbFacility): BaseSection[] {
        let sections: BaseSection[] = [];
        sections.push({
            type: 'heading',
            title: 'Electricity Emission Factors',
            tocInclude: true,
            tocLabel: 'Electricity Emission Factors',
            bookmarkLevel: 1
        });

        const sectionDetails = this.buildElectricityDetails(electricityMeters, facility);
        if (sectionDetails) {
            sections.push(sectionDetails);
        }

        const tableSection = this.buildElectricityTable(emissionDataElectricity);
        if (tableSection) {
            tableSection.pageBreakAfter = true;
            sections.push(tableSection);
        }
        return sections;
    }

    buildElectricityDetails(electricityMeters: string[], facility: IdbFacility): StyledTextSection | undefined {
        const zip = facility.zip;
        const eGrid = facility.eGridSubregion;
        const electricityMetersList: string = electricityMeters.length > 0 ? electricityMeters.join(', ') : '';

        const styledTextSection: StyledTextSection = {
            type: 'styledText',
            content: [
                {
                    text: `\nZip Code: ${zip}\teGRID Subregion: ${eGrid}\nElectricity Meters: ${electricityMetersList}`,
                    fontSize: 12,
                    align: 'center'
                },
                {
                    text: `\n\n`,
                    fontSize: 12,
                    align: 'center'
                }
            ]
        };
        return styledTextSection;
    }

    buildElectricityTable(emissionDataElectricity: Array<EmissionElectricity>): TableSection | undefined {
        let headers: Array<string | TableHeaderCell> = [];
        headers.push({ content: '', colSpan: 1 });
        headers.push({ content: 'Market Emission Rates', colSpan: 3 });
        headers.push({ content: 'Location Emission Rates', colSpan: 3 });
        let subHeadeders: string[] = ['Year', 'CO2 (kg CO2/MWh)', 'CH4 (g CH4/MWh)', 'N2O (g N2O/MWh)', 'CO2 (kg CO2/MWh)', 'CH4 (g CH4/MWh)', 'N2O (g N2O/MWh)'];
        let rows: string[][] = [];

        for (let data of emissionDataElectricity) {
            rows.push([
                data.year.toString(),
                this.checkNumber(data.marketRate.CO2),
                this.checkNumber(data.marketRate.CH4),
                this.checkNumber(data.marketRate.N2O),
                this.checkNumber(data.locationRate.CO2),
                this.checkNumber(data.locationRate.CH4),
                this.checkNumber(data.locationRate.N2O)
            ]);
        }

        const table: TableSection = {
            type: 'table',
            headers,
            subHeaders: subHeadeders,
            rows
        };
        return table;
    }

    buildOtherFuelsSections(emissionData: Array<EmissionOthers>): BaseSection[] {
        let sections: BaseSection[] = [];
        sections.push({
            type: 'heading',
            title: 'Other Emission Factors',
            tocInclude: true,
            tocLabel: 'Other Emission Factors',
            bookmarkLevel: 1
        });

        const tableSection = this.buildOtherFuelsTable(emissionData);
        if (tableSection) {
            tableSection.pageBreakAfter = true;
            sections.push(tableSection);
        }
        return sections;
    }

    buildOtherFuelsTable(emissionData: Array<EmissionOthers>): TableSection | undefined {
        const headers = ['Meter', 'Source', 'Fuel Type', 'CO2 Factor', 'CH4 Factor', 'N2O Factor'];
        let rows: string[][] = [];

        for (let data of emissionData) {
            const fuelType = data.fuelValue !== '' ? data.fuelValue : '\u2014';
            const co2 = data.CO2 ? data.CO2 + ' g CO2/' + data.unit : '\u2014';
            const ch4 = data.CH4 ? data.CH4 + ' g CH4/' + data.unit : '\u2014';
            const n2o = data.N2O ? data.N2O + ' g N2O/' + data.unit : '\u2014';
            rows.push([
                data.meterName,
                data.source,
                fuelType,
                co2,
                ch4,
                n2o
            ]);
        }

        const table: TableSection = {
            type: 'table',
            headers,
            rows
        };
        return table;
    }

    checkNumber(value: number): string {
        if (isNaN(value) || value === null || value === undefined) {
            return '-';
        }
        let roundedValue = Math.round(value * 1000) / 1000;
        return roundedValue.toString();
    }
}

export interface EmissionFactorsInput {
    report: IdbAccountReport;
    accountFacilities: Array<IdbFacility>;
}
