import { ReportDocument } from '@shared/report-output/report-document.model';
import { ReportSection } from '@shared/report-output/report-section.model';
import { AccountEmissionFactorsReportSnapshot } from '@app/v1/reports/shared/emission-factors/emission-factors-report-snapshot';
import { emissionFactorsPdfSections, emissionFactorsPdfText as pdfText } from '@app/v1/reports/shared/emission-factors/emission-factors-pdf';

export function accountEmissionFactorsPdfDocument(snapshot: AccountEmissionFactorsReportSnapshot): ReportDocument {
  const sections: ReportSection[] = [{ type: 'styledText', content: [
    { text: pdfText(snapshot.name), fontSize: 18, bold: true, align: 'center' },
    { text: 'Generated by VERIFI', fontSize: 10, align: 'center' },
    { text: `${pdfText(snapshot.accountName)} | ${snapshot.startYear}-${snapshot.endYear}`, fontSize: 10, align: 'center' }
  ] }];
  snapshot.results.forEach((result, index) => {
    const name = pdfText(result.facility.name);
    sections.push({ type: 'heading', title: name, tocInclude: true, tocLabel: name, bookmarkLevel: 0, pageBreakBefore: index > 0 });
    const categories = emissionFactorsPdfSections(result, 1);
    sections.push(...categories);
    if (!categories.length) sections.push({ type: 'text', content: 'This facility has no meters with applicable emission factors.' });
  });
  return { metadata: { title: pdfText(snapshot.name), subtitle: 'Generated by VERIFI',
    dateGenerated: new Date().toISOString(), skipPage: true, moduleColor: [64, 94, 112] }, sections };
}
