import { inject, Injectable } from '@angular/core';
import { IdbAccount } from '@data/models/idbModels/account';
import { IdbAccountReport } from '@data/models/idbModels/accountReport';
import { BetterClimateReportSetup } from '@data/models/overview-report';
import { BetterClimateAnnualFacilitySummary, BetterClimateReport } from '@domain/calculations/carbon-calculations/betterClimateReport';
import { BetterClimateYearDetails } from '@domain/calculations/carbon-calculations/betterClimateYearsDetails';
import { CustomNumberPipe } from '@v0/shared/helper-pipes/custom-number.pipe';
import { ReportDocument, ReportMetaData } from '@v0/shared/pdf-report/models/report-document.model';
import { BaseSection, ChartSection, StyledTextSection, TableSection, TextSection } from '@v0/shared/pdf-report/models/report-section.model';

const EM_DASH = '\u2014';
const YEARS_PER_TABLE = 7;

export type BetterClimateChartDataOption =
  | 'scope1PercentReductions'
  | 'scope1ReductionContributionRelative'
  | 'scope2MarketPercentReductions'
  | 'scope2MarketReductionContributionRelative'
  | 'scope2LocationPercentReductions'
  | 'scope2LocationReductionContributionRelative';

export interface BetterClimateChartImageProviders {
  absoluteEmissions?: () => Promise<string>;
  emissionsReductions?: () => Promise<string>;
  facilityPerformance?: Partial<Record<BetterClimateChartDataOption, () => Promise<string>>>;
}

export interface BetterClimateReportData {
  account: IdbAccount;
  report: IdbAccountReport;
  reportSettings: BetterClimateReportSetup;
  filteredReport: BetterClimateReport;
  unfilteredReport: BetterClimateReport;
  chartImageProviders?: BetterClimateChartImageProviders;
}

type FacilityScope = 'scope1' | 'scope2Market' | 'scope2Location';
type MetricGroup = 'emissions' | 'reduction' | 'contribution';

interface YearRow {
  label: string;
  value: (detail: BetterClimateYearDetails) => string;
  include?: boolean;
}

@Injectable({ providedIn: 'root' })
export class BetterClimateReportAdapter {
  private readonly customNumberPipe = inject(CustomNumberPipe);

  buildDocument(input: BetterClimateReportData): ReportDocument {
    const metadata: ReportMetaData = {
      title: input.report.name,
      subtitle: 'GENERATED BY VERIFI',
      dateGenerated: new Date().toISOString(),
      moduleColor: [20, 90, 50]
    };
    const sections: BaseSection[] = [];
    const settings = input.reportSettings;

    if (settings.includePortfolioInformation) {
      this.appendSection(sections, 'Portfolio Information', this.buildPortfolioInformation(input));
    }
    if (settings.includeAbsoluteEmissions) {
      this.appendSection(sections, 'Absolute Emissions', this.buildAbsoluteEmissions(input));
    }
    if (settings.includeGHGEmissionsReductions) {
      this.appendSection(sections, 'GHG Emissions Reductions', this.buildEmissionsReductions(input));
    }
    if (settings.includePortfolioEnergyUse) {
      this.appendSection(sections, 'Portfolio Energy Use', this.buildEnergyUseTables(input.filteredReport.portfolioYearDetails, 'total'));
    }
    if (settings.includeStationaryEnergyUse) {
      this.appendSection(sections, 'Stationary Energy Use', this.buildEnergyUseTables(input.filteredReport.portfolioYearDetails, 'stationary'));
    }
    if (settings.includeVehicleEnergyUse) {
      this.appendSection(sections, 'Vehicle Energy Use', this.buildVehicleEnergyUseTables(input.filteredReport.portfolioYearDetails));
    }
    if (settings.includeCalculationsForGraphs) {
      this.appendSection(sections, 'Calculations for Graphs', this.buildGraphCalculationTables(input.filteredReport.portfolioYearDetails));
    }
    if (settings.includeFacilitySummaries) {
      this.appendSection(sections, 'Facility Summaries', this.buildFacilitySummaries(input));
    }

    return { metadata, sections };
  }

  private buildPortfolioInformation(input: BetterClimateReportData): TableSection[] {
    const rows: YearRow[] = [
      { label: 'Square Feet', value: detail => this.number(detail.totalSquareFeet) },
      { label: 'Number of Facilities', value: detail => detail.facilityIds.length.toLocaleString('en-US') }
    ];
    return this.buildYearTables(
      'Portfolio Information',
      input.filteredReport.portfolioYearDetails,
      rows,
      year => input.account.fiscalYear === 'nonCalendarYear' ? `FY - ${year}` : year.toString()
    );
  }

  private buildAbsoluteEmissions(input: BetterClimateReportData): BaseSection[] {
    const details = input.filteredReport.portfolioYearDetails;
    const settings = input.reportSettings;
    const sections: BaseSection[] = [];

    if (settings.includeEmissionsInTables) {
      sections.push(...this.buildYearTables('Emissions (Metric tonne CO2e)', details, this.absoluteEmissionRows(details)));
    }
    if (settings.includePercentReductionsInTables) {
      sections.push(...this.buildYearTables('Percent Reduction', details, this.absolutePercentReductionRows(details)));
    }
    if (settings.includePercentContributionsInTables) {
      sections.push(...this.buildYearTables('Percent Contribution', details, this.absoluteContributionRows(details, settings.emissionsDisplay)));
    }
    sections.push(this.note(`Total emissions shown using ${settings.emissionsDisplay === 'market' ? 'Market-Based' : 'Location-Based'} Scope 2 Emissions.`));
    sections.push(this.chart('Absolute Emissions', input.chartImageProviders?.absoluteEmissions));
    return sections;
  }

  private absoluteEmissionRows(details: BetterClimateYearDetails[]): YearRow[] {
    return [
      { label: 'Scope 1 Emissions', value: detail => this.number(detail.emissionsResults.totalScope1Emissions) },
      { label: 'Stationary Emissions', value: detail => this.number(detail.emissionsResults.stationaryEmissions), include: this.hasValue(details, detail => detail.emissionsResults.stationaryEmissions) },
      { label: 'Mobile Emissions', value: detail => this.number(detail.emissionsResults.mobileTotalEmissions), include: this.hasValue(details, detail => detail.emissionsResults.mobileTotalEmissions) },
      { label: 'Fugitive Emissions', value: detail => this.number(detail.emissionsResults.fugitiveEmissions), include: this.hasValue(details, detail => detail.emissionsResults.fugitiveEmissions) },
      { label: 'Process Emissions', value: detail => this.number(detail.emissionsResults.processEmissions), include: this.hasValue(details, detail => detail.emissionsResults.processEmissions) },
      { label: 'Scope 2 Emissions (Location-Based) from Electricity & District Energy', value: detail => this.number(detail.emissionsResults.locationElectricityEmissions) },
      { label: 'Scope 2 Emissions (Market-Based) from Electricity & District Energy', value: detail => this.number(detail.emissionsResults.marketElectricityEmissions) },
      { label: 'Other Scope 2 Emissions', value: detail => this.number(detail.emissionsResults.otherScope2Emissions) },
      { label: 'Total Emissions (Metric Tons)', value: detail => this.number(detail.totalEmissions) },
      { label: 'Bioenergy and Biomass Emissions', value: detail => this.number(detail.emissionsResults.totalBiogenicEmissions), include: this.hasValue(details, detail => detail.emissionsResults.totalBiogenicEmissions) }
    ];
  }

  private absolutePercentReductionRows(details: BetterClimateYearDetails[]): YearRow[] {
    return [
      { label: 'Scope 1 Emissions', value: detail => this.percent(detail.percentReductions.totalScope1Emissions) },
      { label: 'Stationary Emissions', value: detail => this.percent(detail.percentReductions.stationaryEmissions), include: this.hasValue(details, detail => detail.emissionsResults.stationaryEmissions) },
      { label: 'Mobile Emissions', value: detail => this.percent(detail.percentReductions.mobileTotalEmissions), include: this.hasValue(details, detail => detail.emissionsResults.mobileTotalEmissions) },
      { label: 'Fugitive Emissions', value: detail => this.percent(detail.percentReductions.fugitiveEmissions), include: this.hasValue(details, detail => detail.emissionsResults.fugitiveEmissions) },
      { label: 'Process Emissions', value: detail => this.percent(detail.percentReductions.processEmissions), include: this.hasValue(details, detail => detail.emissionsResults.processEmissions) },
      { label: 'Scope 2 Emissions (Location-Based) from Electricity & District Energy', value: detail => this.percent(detail.percentReductions.locationElectricityEmissions) },
      { label: 'Scope 2 Emissions (Market-Based) from Electricity & District Energy', value: detail => this.percent(detail.percentReductions.marketElectricityEmissions) },
      { label: 'Other Scope 2 Emissions', value: detail => this.percent(detail.percentReductions.otherScope2Emissions) },
      { label: 'Total Emissions', value: detail => this.percent(detail.percentEmissionsReduction) },
      { label: 'Bioenergy and Biomass Emissions', value: detail => this.percent(detail.percentReductions.totalBiogenicEmissions), include: this.hasValue(details, detail => detail.emissionsResults.totalBiogenicEmissions) }
    ];
  }

  private absoluteContributionRows(details: BetterClimateYearDetails[], emissionsDisplay: 'market' | 'location'): YearRow[] {
    return [
      { label: 'Scope 1 Emissions', value: detail => this.percent(detail.totalContribution.totalScope1Emissions) },
      { label: 'Stationary Emissions', value: detail => this.percent(detail.totalContribution.stationaryEmissions), include: this.hasValue(details, detail => detail.emissionsResults.stationaryEmissions) },
      { label: 'Mobile Emissions', value: detail => this.percent(detail.totalContribution.mobileTotalEmissions), include: this.hasValue(details, detail => detail.emissionsResults.mobileTotalEmissions) },
      { label: 'Fugitive Emissions', value: detail => this.percent(detail.totalContribution.fugitiveEmissions), include: this.hasValue(details, detail => detail.emissionsResults.fugitiveEmissions) },
      { label: 'Process Emissions', value: detail => this.percent(detail.totalContribution.processEmissions), include: this.hasValue(details, detail => detail.emissionsResults.processEmissions) },
      { label: 'Scope 2 Emissions (Location-Based) from Electricity & District Energy', value: detail => emissionsDisplay === 'location' ? this.percent(detail.totalContribution.locationElectricityEmissions) : EM_DASH },
      { label: 'Scope 2 Emissions (Market-Based) from Electricity & District Energy', value: detail => emissionsDisplay === 'market' ? this.percent(detail.totalContribution.marketElectricityEmissions) : EM_DASH },
      { label: 'Other Scope 2 Emissions', value: detail => this.percent(detail.totalContribution.otherScope2Emissions) },
      { label: 'Total Emissions', value: detail => this.percent(detail.percentEmissionsReduction) },
      { label: 'Bioenergy and Biomass Emissions', value: detail => this.percent(detail.totalContribution.totalBiogenicEmissions), include: this.hasValue(details, detail => detail.emissionsResults.totalBiogenicEmissions) }
    ];
  }

  private buildEmissionsReductions(input: BetterClimateReportData): BaseSection[] {
    const rows: YearRow[] = [
      { label: 'GHG Emissions Reductions (tonne CO2e)', value: detail => this.number(detail.totalEmissionsReduction) },
      { label: 'GHG Emissions Reductions (%)', value: detail => this.percent(detail.percentEmissionsReduction) }
    ];
    return [
      ...this.buildYearTables('GHG Emissions Reductions', input.filteredReport.portfolioYearDetails, rows),
      this.chart('GHG Emissions Reductions', input.chartImageProviders?.emissionsReductions),
      this.note(`Emissions reductions calculated using ${input.reportSettings.emissionsDisplay === 'market' ? 'Market-Based' : 'Location-Based'} Scope 2 Emissions.`)
    ];
  }

  private buildEnergyUseTables(details: BetterClimateYearDetails[], type: 'total' | 'stationary'): TableSection[] {
    const first = details[0];
    if (!first) {
      return [];
    }
    const fuelTotals = type === 'total' ? first.fuelTotals : first.stationaryFuelTotals;
    const rows: YearRow[] = [
      { label: 'Total Electricity Consumption (MWh)', value: detail => this.number(detail.totalElectricity) },
      { label: 'Renewable Energy Generated and Used On-site (MWh)', value: detail => this.number(detail.onSiteGeneratedElectricity) },
      { label: 'Purchased or Acquired Electricity (MWh)', value: detail => this.number(detail.purchasedElectricity) },
      { label: 'Physical PPAs, Competitive or Utility Products, CCAs, Self-supply (MWh)', value: detail => this.number(detail.pppaElectricity) },
      { label: 'Financial / Virtual PPAs (MWh)', value: detail => this.number(detail.vppaElectricity) },
      { label: 'Unbundled RECs (MWh)', value: detail => this.number(detail.RECs) },
      { label: 'Remaining Grid (MWh)', value: detail => this.number(detail.gridElectricity) },
      ...fuelTotals.map(fuel => ({
        label: `${fuel.fuelType} (MMBtu)`,
        value: (detail: BetterClimateYearDetails) => this.number((type === 'total' ? detail.fuelTotals : detail.stationaryFuelTotals).find(item => item.fuelType === fuel.fuelType)?.total)
      })),
      {
        label: 'Total Energy Use (MMBtu)',
        value: detail => this.number(type === 'total' ? detail.totalEnergyUse : detail.totalStationaryEnergyUse)
      }
    ];
    return this.buildYearTables(type === 'total' ? 'Total Energy Use for Portfolio' : 'Total Stationary Energy Use for Portfolio', details, rows);
  }

  private buildVehicleEnergyUseTables(details: BetterClimateYearDetails[]): TableSection[] {
    const first = details[0];
    if (!first) {
      return [];
    }
    const rows: YearRow[] = [
      ...first.vehicleFuelTotals.map(fuel => ({
        label: `${fuel.fuelType} (MMBtu)`,
        value: (detail: BetterClimateYearDetails) => this.number(detail.vehicleFuelTotals.find(item => item.fuelType === fuel.fuelType)?.total)
      })),
      { label: 'Total Energy Use (MMBtu)', value: detail => this.number(detail.totalVehicleEnergyUse) }
    ];
    return this.buildYearTables('Energy Use for Vehicles', details, rows);
  }

  private buildGraphCalculationTables(details: BetterClimateYearDetails[]): TableSection[] {
    const calculationRows: YearRow[] = [
      { label: 'Goal for Emissions', value: detail => detail === details[0] ? this.number(detail.goalForEmissions) : EM_DASH },
      { label: 'Annual Percent Improvement', value: detail => this.percent(detail.annualPercentImprovement) },
      { label: 'Scope 2 Total Energy Use (MMBtu)', value: detail => this.number(detail.scope2EnergyUse) },
      { label: 'Portfolio Average Scope 2 Emission Factor - Market Based (kg CO2e/MMBtu)', value: detail => this.number(detail.scope2MarketEmissionsFactor) },
      { label: 'Portfolio Average Scope 2 Emission Factor - Location Based (kg CO2e/MMBtu)', value: detail => this.number(detail.scope2LocationEmissionsFactor) },
      { label: 'Decrease in Scope 2 Energy Use (MMBtu)', value: detail => this.number(detail.decreaseInScope2EnergyUse) },
      { label: 'Increase in Onsite Renewable Energy Use (MMBtu)', value: detail => this.number(detail.increaseInOnsiteRenewables) },
      { label: 'Increase in Offsite Renewable Energy Use (MMBtu)', value: detail => this.number(detail.increaseInOffsiteRenewables) },
      { label: 'Emissions Reduction from Change in Scope 2 Emissions Factor (Metric tonne CO2e)', value: detail => this.number(detail.emissionsReductionChange) }
    ];
    const reductionRows: YearRow[] = [
      { label: 'Scope 1 Stationary', value: detail => this.number(detail.reductions.stationaryEmissions) },
      { label: 'Scope 1 Mobile', value: detail => this.number(detail.reductions.mobileTotalEmissions) },
      { label: 'Scope 1 Fugitive & Process', value: detail => this.number(detail.reductions.fugitiveEmissions) },
      { label: 'Scope 2 Change in Energy Use', value: detail => this.number(detail.scope2ChangeInEnergyUse) },
      { label: 'Scope 2 On-site Renewables', value: detail => this.number(detail.scope2OnsiteRenewablesReductions) },
      { label: 'Scope 2 Off-site Renewables', value: detail => this.number(detail.scope2OffsiteRenewablesReductions) },
      { label: 'Scope 2 Greening of Grid / Other', value: detail => this.number(detail.scope2GreenOfGridReductions) },
      { label: 'Total', value: detail => this.number(detail.totalEmissionsReduction) }
    ];
    return [
      ...this.buildYearTables('Calculations for Graphs', details, calculationRows),
      ...this.buildYearTables('Emissions Reduction Components', details, reductionRows)
    ];
  }

  private buildFacilitySummaries(input: BetterClimateReportData): BaseSection[] {
    const sections: BaseSection[] = [];
    const scopes: Array<{ scope: FacilityScope; title: string }> = [
      { scope: 'scope1', title: 'Scope 1 Facility Emissions' },
      { scope: 'scope2Market', title: 'Scope 2 Market-Based Facility Emissions' },
      { scope: 'scope2Location', title: 'Scope 2 Location-Based Facility Emissions' }
    ];
    for (const { scope, title } of scopes) {
      const scopeSections: BaseSection[] = [];
      if (input.reportSettings.includePercentReductionsInTables) {
        scopeSections.push(this.buildTopPerformersTable(input.filteredReport, input.reportSettings, scope, 'reduction'));
      }
      if (input.reportSettings.includePercentContributionsInTables) {
        scopeSections.push(this.buildTopPerformersTable(input.filteredReport, input.reportSettings, scope, 'contribution'));
      }
      if (input.reportSettings.includePercentReductionsInTables) {
        scopeSections.push(this.chart(`${title}: Savings by Facility`, input.chartImageProviders?.facilityPerformance?.[this.chartOption(scope, 'reduction')]));
      }
      if (input.reportSettings.includePercentContributionsInTables) {
        scopeSections.push(this.chart(`${title}: Contribution by Facility`, input.chartImageProviders?.facilityPerformance?.[this.chartOption(scope, 'contribution')]));
      }
      if (input.reportSettings.includeEmissionsInTables) {
        scopeSections.push(...this.buildFacilityTables(input.filteredReport, scope, 'emissions', 'Emissions (Metric tonne CO2e)'));
      }
      if (input.reportSettings.includePercentReductionsInTables) {
        scopeSections.push(...this.buildFacilityTables(input.filteredReport, scope, 'reduction', 'Percent Reduction'));
      }
      if (input.reportSettings.includePercentContributionsInTables) {
        scopeSections.push(...this.buildFacilityTables(input.filteredReport, scope, 'contribution', 'Percent Contribution'));
      }
      this.appendSection(sections, title, scopeSections, 1);
    }
    return sections;
  }

  private buildTopPerformersTable(report: BetterClimateReport, settings: BetterClimateReportSetup, scope: FacilityScope, metric: Exclude<MetricGroup, 'emissions'>): TableSection {
    const ordered = [...(report.annualFacilitiesSummaries ?? [])].sort((left, right) => {
      return this.facilityMetric(this.reportYearDetail(right, report.reportYear), scope, metric) - this.facilityMetric(this.reportYearDetail(left, report.reportYear), scope, metric);
    });
    const valueLabel = metric === 'reduction' ? 'Savings' : 'Contribution';
    const rows: string[][] = [];
    for (let index = 0; index < settings.numberOfTopPerformers; index++) {
      const high = ordered[index];
      const low = ordered[ordered.length - index - 1];
      rows.push([
        (index + 1).toString(),
        high?.facility.name ?? EM_DASH,
        high ? this.percent(this.facilityMetric(this.reportYearDetail(high, report.reportYear), scope, metric)) : EM_DASH,
        low?.facility.name ?? EM_DASH,
        low ? this.percent(this.facilityMetric(this.reportYearDetail(low, report.reportYear), scope, metric)) : EM_DASH
      ]);
    }
    return {
      type: 'table',
      title: `${valueLabel} Leaders`,
      headers: ['Change', `Top ${settings.numberOfTopPerformers}`, valueLabel, `Low ${settings.numberOfTopPerformers}`, valueLabel],
      rows
    };
  }

  private buildFacilityTables(report: BetterClimateReport, scope: FacilityScope, metric: MetricGroup, title: string): TableSection[] {
    const yearChunks = this.chunks(report.portfolioYearDetails ?? [], YEARS_PER_TABLE);
    const orderedFacilities = [...(report.annualFacilitiesSummaries ?? [])].sort((left, right) => {
      return this.facilityMetric(this.reportYearDetail(right, report.reportYear), scope, 'emissions') - this.facilityMetric(this.reportYearDetail(left, report.reportYear), scope, 'emissions');
    });
    return yearChunks.map((years, index) => ({
      type: 'table',
      title: this.chunkTitle(title, years, yearChunks.length, index),
      pageBreakBefore: index > 0 ? false : undefined,
      tocInclude: index > 0 ? false : undefined,
      headers: ['Facility Name', ...years.map(detail => detail.year.toString())],
      rows: [
        ...orderedFacilities.map(summary => [
          summary.facility.name,
          ...years.map(year => this.facilityValue(this.yearDetail(summary, year.year), scope, metric))
        ]),
        ['Totals', ...years.map(year => this.facilityTotalValue(year, scope, metric))]
      ]
    }));
  }

  private facilityValue(detail: BetterClimateYearDetails | undefined, scope: FacilityScope, metric: MetricGroup): string {
    const value = this.facilityMetric(detail, scope, metric);
    return metric === 'emissions' ? this.number(value) : this.percent(value);
  }

  private facilityTotalValue(detail: BetterClimateYearDetails, scope: FacilityScope, metric: MetricGroup): string {
    if (metric === 'contribution') {
      return this.percent(this.facilityMetric(detail, scope, 'reduction'));
    }
    return this.facilityValue(detail, scope, metric);
  }

  private facilityMetric(detail: BetterClimateYearDetails | undefined, scope: FacilityScope, metric: MetricGroup): number {
    if (!detail) {
      return 0;
    }
    if (scope === 'scope1') {
      return metric === 'emissions' ? detail.emissionsResults.totalScope1Emissions
        : metric === 'reduction' ? detail.percentReductions.totalScope1Emissions
          : detail.relativeContribution.totalScope1Emissions;
    }
    if (scope === 'scope2Market') {
      return metric === 'emissions' ? detail.emissionsResults.scope2MarketEmissions
        : metric === 'reduction' ? detail.percentReductions.scope2MarketEmissions
          : detail.relativeContribution.scope2MarketEmissions;
    }
    return metric === 'emissions' ? detail.emissionsResults.scope2LocationEmissions
      : metric === 'reduction' ? detail.percentReductions.scope2LocationEmissions
        : detail.relativeContribution.scope2LocationEmissions;
  }

  private chartOption(scope: FacilityScope, metric: Exclude<MetricGroup, 'emissions'>): BetterClimateChartDataOption {
    const suffix = metric === 'reduction' ? 'PercentReductions' : 'ReductionContributionRelative';
    return `${scope}${suffix}` as BetterClimateChartDataOption;
  }

  private reportYearDetail(summary: BetterClimateAnnualFacilitySummary | undefined, reportYear: number): BetterClimateYearDetails | undefined {
    return summary?.betterClimateYearDetails.find(detail => detail.year === reportYear);
  }

  private yearDetail(summary: BetterClimateAnnualFacilitySummary, year: number): BetterClimateYearDetails | undefined {
    return summary.betterClimateYearDetails.find(detail => detail.year === year);
  }

  private buildYearTables(title: string, details: BetterClimateYearDetails[], rows: YearRow[], yearLabel: (year: number) => string = year => year.toString()): TableSection[] {
    const includedRows = rows.filter(row => row.include !== false);
    const yearChunks = this.chunks(details ?? [], YEARS_PER_TABLE);
    return yearChunks.map((years, index) => ({
      type: 'table',
      title: this.chunkTitle(title, years, yearChunks.length, index),
      pageBreakBefore: index > 0 ? false : undefined,
      tocInclude: index > 0 ? false : undefined,
      headers: ['', ...years.map(detail => yearLabel(detail.year))],
      rows: includedRows.map(row => [row.label, ...years.map(detail => row.value(detail))])
    }));
  }

  private chunks<T>(values: T[], size: number): T[][] {
    const chunks: T[][] = [];
    for (let index = 0; index < values.length; index += size) {
      chunks.push(values.slice(index, index + size));
    }
    return chunks;
  }

  private chunkTitle(title: string, years: BetterClimateYearDetails[], chunkCount: number, chunkIndex: number): string {
    if (chunkCount <= 1 || years.length === 0) {
      return title;
    }
    return `${title} (${years[0].year}-${years[years.length - 1].year}${chunkIndex > 0 ? ', continued' : ''})`;
  }

  private appendSection(sections: BaseSection[], title: string, content: BaseSection[], bookmarkLevel = 0): void {
    const previousSection = sections[sections.length - 1];
    const containsNestedSections = content.some(section => section.type === 'styledText');
    const hasTable = content.some(section => section.type === 'table');
    const hasGraph = content.some(section => section.type === 'chart');
    const needsContentTypeSuffix = hasTable && hasGraph;
    let hasTableBookmark = false;
    let hasGraphBookmark = false;
    sections.push(this.divider(title, bookmarkLevel, sections.length > 0 && previousSection?.pageBreakAfter !== true));
    content.forEach((section, index) => {
      const isTableOrChart = section.type === 'table' || section.type === 'chart';
      const followsDividerPage = content[index - 1]?.type === 'styledText' && content[index - 1]?.pageBreakAfter === true;
      if (index > 0 && isTableOrChart && !followsDividerPage && section.pageBreakBefore !== false) {
        section.pageBreakBefore = true;
      }
      if (isTableOrChart && !containsNestedSections) {
        const alreadyBookmarked = section.type === 'table' ? hasTableBookmark : hasGraphBookmark;
        if (!alreadyBookmarked && section.tocInclude !== false) {
          section.tocInclude = true;
          section.tocLabel = needsContentTypeSuffix
            ? `${title} ${section.type === 'table' ? 'table' : 'Graph'}`
            : title;
          section.bookmarkLevel = 1;
          if (section.type === 'table') {
            hasTableBookmark = true;
          } else {
            hasGraphBookmark = true;
          }
        } else {
          section.tocInclude = false;
          section.tocLabel = undefined;
          section.bookmarkLevel = undefined;
        }
      }
      sections.push(section);
    });
  }

  private divider(title: string, bookmarkLevel: number, pageBreakBefore = false): StyledTextSection {
    return {
      type: 'styledText',
      content: [{ text: title, fontSize: 16, bold: true, align: 'center' }],
      verticalCenter: true,
      pageBreakBefore,
      pageBreakAfter: true,
      tocInclude: true,
      tocLabel: title,
      bookmarkLevel: bookmarkLevel === 0 ? 0 : 1
    };
  }

  private chart(title: string, imageDataProvider?: () => Promise<string>): ChartSection {
    return { type: 'chart', title, imageDataProvider };
  }

  private note(content: string): TextSection {
    return { type: 'text', content };
  }

  private hasValue(details: BetterClimateYearDetails[], selector: (detail: BetterClimateYearDetails) => number): boolean {
    return details.some(detail => Boolean(selector(detail)));
  }

  private number(value: number | undefined | null): string {
    if (value === null || value === undefined || value === 0 || !Number.isFinite(value)) {
      return EM_DASH;
    }
    return this.customNumberPipe.transform(value) ?? EM_DASH;
  }

  private percent(value: number | undefined | null): string {
    if (value === null || value === undefined || value === 0 || !Number.isFinite(value)) {
      return EM_DASH;
    }
    return `${value.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}%`;
  }
}
