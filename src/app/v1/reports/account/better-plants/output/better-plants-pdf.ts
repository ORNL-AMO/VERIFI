import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import type { CellInput, RowInput } from 'jspdf-autotable';
import { BetterPlantsImages } from '@platform/reports/better-plants-assets.service';
import { AnalysisResultNumberPipe } from '@app/v1/shared/analysis-results/number/analysis-result-number.pipe';
import { BetterPlantsDocument, BetterPlantsPage, BetterPlantsRow } from '../better-plants-report.view';

const MARGIN = 12;
const CONTENT_WIDTH = 215.9 - MARGIN * 2;
const BLUE: [number, number, number] = [30, 81, 126];
const number = new AnalysisResultNumberPipe();

/** Official-form composition is report-owned; it never reads the preview DOM. */
export async function composeBetterPlantsPdf(document: BetterPlantsDocument, images: BetterPlantsImages,
  signal?: AbortSignal): Promise<Blob> {
  signal?.throwIfAborted();
  if (!document.pages.length) throw new Error('No Better Plants report periods are available.');
  const pdf = new jsPDF({ unit: 'mm', format: 'letter', orientation: 'portrait', compress: true });
  pdf.setProperties({ title: document.name, subject: 'Better Plants annual reporting form', creator: 'VERIFI' });
  const banner = pdf.getImageProperties(images.banner), footer = pdf.getImageProperties(images.footer);
  const bannerHeight = Math.min(30, CONTENT_WIDTH * banner.height / banner.width);
  const footerHeight = Math.min(15, CONTENT_WIDTH * footer.height / footer.width);
  const bottom = 279.4 - footerHeight - 15;
  const pageYears = new Map<number, number>();
  const continuationHeaders = new Set<number>();
  let y = MARGIN, initialPage = 1, reportYear = document.pages[0].year;

  const markPage = () => pageYears.set(pdf.getCurrentPageInfo().pageNumber, reportYear);
  const continuationHeader = () => {
    const page = pdf.getCurrentPageInfo().pageNumber;
    markPage();
    if (page === initialPage || continuationHeaders.has(page)) return;
    pdf.setFont('helvetica', 'bold'); pdf.setFontSize(9); pdf.setTextColor(...BLUE);
    pdf.text(`Better Plants ${reportYear} - Continued`, MARGIN, 13);
    pdf.setFont('helvetica', 'normal'); pdf.setFontSize(8); pdf.setTextColor(50);
    const name = pdf.splitTextToSize(document.name, CONTENT_WIDTH) as string[];
    pdf.text(name.slice(0, 2), MARGIN, 18);
    continuationHeaders.add(page);
  };
  const nextPage = () => { pdf.addPage(); y = 30; continuationHeader(); };
  const ensure = (height: number) => { if (y + height > bottom) nextPage(); };
  const paragraph = (text: string, bold = false, size = 9) => {
    pdf.setFont('helvetica', bold ? 'bold' : 'normal'); pdf.setFontSize(size); pdf.setTextColor(35);
    const lines = pdf.splitTextToSize(text, CONTENT_WIDTH) as string[];
    for (const line of lines) { signal?.throwIfAborted(); ensure(4.5); pdf.text(line, MARGIN, y); y += 4.5; }
    y += 2;
  };
  const heading = (title: string) => { ensure(22); paragraph(title, true, 10); };
  const table = (title: string, headers: CellInput[], rows: RowInput[], totalRows: readonly number[] = []) => {
    signal?.throwIfAborted();
    heading(title);
    autoTable(pdf, {
      head: [headers], body: rows, startY: y, margin: { top: 30, left: MARGIN, right: MARGIN, bottom: footerHeight + 15 },
      tableWidth: CONTENT_WIDTH, theme: 'grid', rowPageBreak: 'avoid', showHead: 'everyPage',
      styles: { font: 'helvetica', fontSize: 8, cellPadding: 1.8, textColor: [35, 35, 35], lineColor: [125, 145, 160], lineWidth: .15 },
      headStyles: { fillColor: BLUE, textColor: [255, 255, 255], fontStyle: 'bold', halign: 'center' },
      columnStyles: { 0: { cellWidth: headers.length === 5 ? 90 : 110 }, 1: { halign: 'right' }, 2: { halign: 'right' }, 3: { halign: 'right' }, 4: { halign: 'right' } },
      didParseCell: data => {
        if (data.section === 'body' && totalRows.includes(data.row.index)) {
          data.cell.styles.fontStyle = 'bold'; data.cell.styles.fillColor = [235, 243, 248];
        }
      },
      willDrawPage: () => { signal?.throwIfAborted(); continuationHeader(); }
    });
    y = (pdf as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 7;
  };

  for (let index = 0; index < document.pages.length; index++) {
    signal?.throwIfAborted();
    const page = document.pages[index]; reportYear = page.year;
    if (index) pdf.addPage();
    initialPage = pdf.getCurrentPageInfo().pageNumber; markPage(); y = MARGIN;
    pdf.addImage(images.banner, 'JPEG', MARGIN, y, CONTENT_WIDTH, bannerHeight); y += bannerHeight + 7;
    paragraph(document.name, true, 13);
    paragraph(`Generated by VERIFI - ${page.water ? 'Water' : 'Energy'} Annual Reporting Form - ${page.reportLabel}`, false, 9);
    const company = document.company;
    table('Company and contact information', ['Participating company', 'Contact information'], [[
      [company.name, company.address, company.naics ? `NAICS of Participating Plants: ${company.naics}` : ''].filter(Boolean).join('\n'),
      `Name: ${company.contactName}\nPhone: ${company.contactPhone}\nEmail: ${company.contactEmail}`
    ]]);
    table('Participating plants', ['Participating plants', `Baseline Year\n${page.baselineLabel}`, `Report Year\n${page.reportLabel}`], comparisonRows(page.counts));
    table(`Primary ${page.water ? 'Water Consumed (kGal)' : 'Energy Consumed (MMBtu)'}`,
      page.water ? ['Water source', 'Baseline Year', 'Metered or Estimated?', 'Report Year', 'Metered or Estimated?']
        : ['Energy source', 'Baseline Year', 'Report Year'], consumptionRows(page), totalIndices(page.consumption));
    const metrics = page.waterPilot ? [...page.metrics, page.waterPilot] : page.metrics;
    table('Baseline adjustments and intensity improvement', ['Measure', 'Baseline Year', 'Report Year'], comparisonRows(metrics), totalIndices(metrics));
    if (page.water) {
      heading('If a baseline adjustment was made, please indicate the reason for making the adjustment');
      paragraph(page.waterAdjustment || 'N/A');
    }
    if (page.waterMetricUnits) paragraph(`Units for water intensity metric: ${page.waterMetricUnits}`);
    if (page.additionalWater) paragraph('++ Indicates water consumption is not included in intensity metric for tracking.', false, 8);
    paragraph('* Participating plants should only include those located in the United States.', false, 8);
    paragraph("** Please refer to the DOE's Energy Baseline Guidance document to determine changes in intensity. Improvement in performance should be reported as a positive number.", false, 8);
    for (const note of page.notes) { heading(note.label); paragraph(note.text); }
    if (page.performance.length) {
      table(`Facility-level ${page.water ? 'Water' : 'Energy'} Performance (Applies to Companies with Multiple Plants)`,
        document.includeFacilityNames ? ['Intensity Performance Level', 'Number of Facilities', 'Facilities'] : ['Intensity Performance Level', 'Number of Facilities'],
        page.performance.map(band => document.includeFacilityNames
          ? [band.label, band.count ? String(band.count) : '—', band.facilities.join('\n') || '—']
          : [band.label, band.count ? String(band.count) : '—']));
    }
  }
  const pages = pdf.getNumberOfPages();
  for (let page = 1; page <= pages; page++) {
    signal?.throwIfAborted(); pdf.setPage(page);
    const width = footerHeight * footer.width / footer.height;
    pdf.addImage(images.footer, 'PNG', (215.9 - width) / 2, 279.4 - footerHeight - 8, width, footerHeight);
    pdf.setFont('helvetica', 'normal'); pdf.setFontSize(7); pdf.setTextColor(80);
    pdf.text(`Better Plants ${pageYears.get(page)} - ${page} / ${pages}`, 215.9 - MARGIN, 275.5, { align: 'right' });
  }
  signal?.throwIfAborted();
  return pdf.output('blob');
}

function comparisonRows(rows: readonly BetterPlantsRow[]): RowInput[] {
  return rows.map(row => [row.label, number.transform(row.baseline), row.percent
    ? `${Number.isFinite(row.report) ? row.report!.toLocaleString(undefined, { minimumFractionDigits: 0, maximumFractionDigits: 2 }) : '—'} %`
    : number.transform(row.report)]);
}

function consumptionRows(page: BetterPlantsPage): RowInput[] {
  return page.consumption.map(row => {
    const label = row.label + (row.additional ? ' ++' : '');
    return page.water ? [label, number.transform(row.baseline), row.baselineMetered ?? '—', number.transform(row.report), row.reportMetered ?? '—']
      : [label, number.transform(row.baseline), number.transform(row.report)];
  });
}

function totalIndices(rows: readonly BetterPlantsRow[]): number[] {
  return rows.flatMap((row, index) => row.total ? [index] : []);
}
