import { AccountWorkspaceQueryService } from 'src/app/account-workspace/account-workspace-query.service';
import { inject, Injectable } from '@angular/core';
import { CostSavingsReportSettings, IdbFacilityReport, MonthlyGroupData, YearGroupData } from "src/app/models/idbModels/facilityReport";
import { ReportDocument, ReportMetaData } from "src/app/shared/pdf-report/models/report-document.model";
import { BaseSection, ChartSection, StyledTextSection, TableSection } from "src/app/shared/pdf-report/models/report-section.model";
import { CustomNumberPipe } from "src/app/shared/helper-pipes/custom-number.pipe";
import { IdbFacility } from "src/app/models/idbModels/facility";
import { AnalysisGroup } from "src/app/models/analysis";

@Injectable({ providedIn: 'root' })
export class FacilityCostSavingsReportAdapter {
    private readonly accountWorkspaceQuery = inject(AccountWorkspaceQueryService);
    private customNumberPipe: CustomNumberPipe = inject(CustomNumberPipe);

    report: IdbFacilityReport;
    reportSettings: CostSavingsReportSettings;
    filteredGroups: Array<AnalysisGroup>;
    years: Array<number>;
    finalUnit: string;

    buildDocument(input: FacilityCostSavingsReportData): ReportDocument {
        const sections: BaseSection[] = [];
        this.report = input.facilityReport;
        this.reportSettings = this.report.costSavingsReportSettings;
        this.filteredGroups = input.filteredGroups;
        this.years = input.years;
        this.finalUnit = input.finalUnit;

        let metadata: ReportMetaData = {
            title: `${this.report.name}`,
            subtitle: 'GENERATED BY VERIFI',
            dateGenerated: new Date().toISOString(),
            moduleColor: [46, 81, 127]
        };

        const facilitySections: BaseSection[] = [];
        if (this.reportSettings.includeFacility && this.reportSettings.includeAnnual && this.reportSettings.annualSavingsTable && input.costSavingsTable) {
            const tableSection = this.buildAnnualSavingsTable(input.costSavingsTable, 'Annual Avoided Cost Savings');
            if (tableSection) {
                facilitySections.push(tableSection);
            }
        }
        if (this.reportSettings.includeFacility && this.reportSettings.includeAnnual && this.reportSettings.annualSavingsGraph) {
            const graphSection = this.createChartSection(input.chartImageProviders?.annualCostSavingsGraph, 'Annual Avoided Cost Savings Graph');
            if (graphSection) {
                facilitySections.push(graphSection);
            }
        }
        if (this.reportSettings.includeFacility && this.reportSettings.includeMonthly && this.reportSettings.monthlySavingsTable && input.monthlyCostSavingsTable) {
            const tableSection = this.buildMonthlySavingsTable(input.monthlyCostSavingsTable, input.monthKeys, 'Monthly Avoided Cost Savings');
            if (tableSection) {
                facilitySections.push(tableSection);
            }
        }
        if (this.reportSettings.includeFacility && this.reportSettings.includeMonthly && this.reportSettings.monthlySavingsGraph) {
            const graphSection = this.createChartSection(input.chartImageProviders?.monthlyCostSavingsGraph, 'Monthly Avoided Cost Savings Graph');
            if (graphSection) {
                facilitySections.push(graphSection);
            }
        }
        if (this.reportSettings.includeFacility && this.reportSettings.includeAnnual && this.reportSettings.annualCumulativeSavingsTable) {
            const tableSection = this.buildAnnualSavingsTable(input.cumulativeCostSavingsTable, 'Cumulative Annual Avoided Cost Savings');
            if (tableSection) {
                facilitySections.push(tableSection);
            }
        }
        if (this.reportSettings.includeFacility && this.reportSettings.includeAnnual && this.reportSettings.annualCumulativeSavingsGraph) {
            const graphSection = this.createChartSection(input.chartImageProviders?.cumulativeAnnualCostSavingsGraph, 'Cumulative Annual Avoided Cost Savings Graph');
            if (graphSection) {
                facilitySections.push(graphSection);
            }
        }
        if (this.reportSettings.includeFacility && this.reportSettings.includeMonthly && this.reportSettings.monthlyCumulativeSavingsTable) {
            const tableSection = this.buildMonthlySavingsTable(input.cumulativeMonthlyCostSavingsTable, input.monthKeys, 'Cumulative Monthly Avoided Cost Savings');
            if (tableSection) {
                facilitySections.push(tableSection);
            }
        }
        if (this.reportSettings.includeFacility && this.reportSettings.includeMonthly && this.reportSettings.monthlyCumulativeSavingsGraph) {
            const graphSection = this.createChartSection(input.chartImageProviders?.cumulativeMonthlyCostSavingsGraph, 'Cumulative Monthly Avoided Cost Savings Graph');
            if (graphSection) {
                facilitySections.push(graphSection);
            }
        }
        if (this.reportSettings.userCostSummary && input.costDataTable) {
            const tableSection = this.buildCostDataTable(input.costDataTable, 'Summary of User Costs', input.groupUnits);
            if (tableSection) {
                facilitySections.push(tableSection);
            }
        }
        if (this.reportSettings.calculatedCostSummary && input.convertedCostDataTable) {
            const tableSection = this.buildCostDataTable(input.convertedCostDataTable, 'Summary of Calculated Costs');
            if (tableSection) {
                facilitySections.push(tableSection);
            }
        }
        if (facilitySections.length > 0) {
            const titleSection = this.buildTitleSection('Facility Results');
            if (titleSection) {
                sections.push(titleSection);
            }
            sections.push(...facilitySections);
        }
        if (this.reportSettings.includeGroup) {
            for (const group of this.filteredGroups) {
                let groupSections: BaseSection[] = [];
                if (this.reportSettings.groupActualVsAdjustedTable) {
                    const tableSection = this.buildGroupActualVsAdjustedTable(group, input.estimatedEnergyCostTable, input.expectedEnergyCostTable, 'Energy Cost Comparison');
                    if (tableSection) {
                        groupSections.push(tableSection);
                    }
                    const graphSection = this.createChartSection(input.chartImageProviders?.groupComparisonGraph?.[group.idbGroupId], 'Energy Cost Comparison Graph');
                    if (graphSection) {
                        groupSections.push(graphSection);
                    }
                }
                if (this.reportSettings.groupAnnualTable) {
                    const tableSection = this.buildGroupSavingsTable(group, input.costSavingsTable, input.energyUseTable, input.adjustedEnergyUseTable, input.energySavingsTable, input.estimatedEnergyCostTable, input.expectedEnergyCostTable, input.cumulativeCostSavingsTable, 'Annual Details', this.years, false);
                    if (tableSection) {
                        groupSections.push(tableSection);
                    }
                }
                if (this.reportSettings.groupMonthlyTable) {
                    const tableSection = this.buildGroupSavingsTable(group, input.monthlyCostSavingsTable, input.monthlyEnergyUseTable, input.adjustedMonthlyEnergyUseTable, input.monthlyEnergySavingsTable, input.estimatedMonthlyEnergyCostTable, input.expectedMonthlyEnergyCostTable, input.cumulativeMonthlyCostSavingsTable, 'Monthly Details', input.monthKeys, true);
                    if (tableSection) {
                        groupSections.push(tableSection);
                    }
                }
                if (groupSections.length > 0) {
                    const titleSectionGroup = this.buildTitleSection(this.accountWorkspaceQuery.getMeterGroupName(group.idbGroupId));
                    if (titleSectionGroup) {
                        sections.push(titleSectionGroup);
                    }
                    sections.push(...groupSections);
                }
            }
        }


        return {
            metadata,
            sections
        };
    }

    buildTitleSection(title: string): StyledTextSection | undefined {
        const section: StyledTextSection = {
            type: 'styledText',
            verticalCenter: true,
            content: [
                {
                    text: title,
                    fontSize: 16,
                    bold: true,
                    align: 'center'
                }
            ],
            pageBreakAfter: true,
            tocInclude: true,
            tocLabel: title,
            bookmarkLevel: 0
        };
        return section;
    }

    buildAnnualSavingsTable(costSavingsTable: YearGroupData, title: string): TableSection | undefined {
        let headers: string[] = ['Year'];
        let rows: string[][] = [];
        for (const group of this.filteredGroups) {
            headers.push(this.accountWorkspaceQuery.getMeterGroupName(group.idbGroupId));
        }
        headers.push('Total');

        const years = this.years.sort((a, b) => a - b).slice(1);
        for (const year of years) {
            let row: string[] = [];
            row.push(year.toString());
            for (const group of this.filteredGroups) {
                const yearValue = this.getValue(year, group.idbGroupId, costSavingsTable);
                row.push(`${this.checkNumber(yearValue, true)}`);
            }
            row.push(`${this.checkNumber(this.getTotal(year, costSavingsTable), true)}`);
            rows.push(row);
        }

        let tableSection: TableSection = {
            type: 'table',
            title: title,
            headers,
            rows,
            pageBreakAfter: true,
            tocInclude: true,
            tocLabel: title,
            bookmarkLevel: 1
        }
        return tableSection;
    }

    buildMonthlySavingsTable(monthlyCostSavingsTable: MonthlyGroupData, monthKeys: Array<string>, title: string): TableSection | undefined {
        let headers: string[] = ['Month'];
        let rows: string[][] = [];
        if (monthKeys.length > 12) {
            monthKeys = monthKeys.slice(12);
        }

        for (const group of this.filteredGroups) {
            headers.push(this.accountWorkspaceQuery.getMeterGroupName(group.idbGroupId));
        }
        headers.push('Total');

        for (const monthKey of monthKeys) {
            let row: string[] = [];
            row.push(this.formatMonthLabel(monthKey));
            for (const group of this.filteredGroups) {
                const monthValue = monthlyCostSavingsTable[monthKey]?.[group.idbGroupId] ?? 0;
                row.push(`${this.checkNumber(monthValue, true)}`);
            }
            row.push(`${this.checkNumber(this.getMonthlyTotal(monthKey, monthlyCostSavingsTable), true)}`);
            rows.push(row);
        }

        let tableSection: TableSection = {
            type: 'table',
            title: title,
            headers,
            rows,
            pageBreakAfter: true,
            tocInclude: true,
            tocLabel: title,
            bookmarkLevel: 1
        };
        return tableSection;
    }

    buildCostDataTable(costDataTable: YearGroupData, title: string, groupUnits?: { [groupId: string]: string }): TableSection | undefined {
        let headers: string[] = ['Year'];
        let subHeaders: string[] = [''];
        let rows: string[][] = [];
        for (const group of this.filteredGroups) {
            headers.push(this.accountWorkspaceQuery.getMeterGroupName(group.idbGroupId));
            if (!groupUnits) {
                subHeaders.push(`$/${this.finalUnit ?? ''}`);
            }
            else {
                subHeaders.push(`$/${groupUnits[group.idbGroupId] ?? ''}`);
            }
        }

        for (const year of this.years) {
            let row: string[] = [];
            row.push(year.toString());
            for (const group of this.filteredGroups) {
                const value = this.getValue(year, group.idbGroupId, costDataTable);
                row.push(`${this.checkCostSummaryNumber(value)}`);
            }
            rows.push(row);
        }

        let tableSection: TableSection = {
            type: 'table',
            title: title,
            headers,
            subHeaders,
            rows,
            pageBreakAfter: true,
            tocInclude: true,
            tocLabel: title,
            bookmarkLevel: 1
        };
        return tableSection;
    }

    buildGroupActualVsAdjustedTable(group: AnalysisGroup, estimatedEnergyCostTable: YearGroupData, expectedEnergyCostTable: YearGroupData, title: string): TableSection | undefined {
        let headers = ['Year', 'Actual Cost', 'Adjusted Cost'];
        let rows: string[][] = [];
        for (const year of this.years) {
            const actualCost = this.getValue(year, group.idbGroupId, estimatedEnergyCostTable);
            const adjustedCost = this.getValue(year, group.idbGroupId, expectedEnergyCostTable);
            rows.push([year.toString(), `${this.checkNumber(actualCost, true)}`, `${this.checkNumber(adjustedCost, true)}`]);
        }

        let tableSection: TableSection = {
            type: 'table',
            title: title,
            headers,
            rows,
            pageBreakAfter: true,
            tocInclude: true,
            tocLabel: title,
            bookmarkLevel: 1
        };
        return tableSection;
    }

    buildGroupSavingsTable(group: AnalysisGroup, costSavingsTable: YearGroupData, energyUseTable: YearGroupData, adjustedEnergyUseTable: YearGroupData, energySavingsTable: YearGroupData, estimatedEnergyCostTable: YearGroupData, expectedEnergyCostTable: YearGroupData, cumulativeCostSavingsTable: YearGroupData, title: string, rowKeys: (string | number)[], isMonthly: boolean): TableSection | undefined {
        let headers: string[] = [];
        if (!isMonthly) {
            headers = ['Year', 'Actual Use', 'Actual Cost', 'Adjusted Use', 'Adjusted Cost', 'Enery Savings', 'Avoided Cost Savings', 'Cumulative Avoided Cost Savings'];
        }
        else {
            headers = ['Month', 'Actual Use', 'Actual Cost', 'Adjusted Use', 'Adjusted Cost', 'Enery Savings', 'Avoided Cost Savings', 'Cumulative Avoided Cost Savings'];
        }
        let subheaders = ['', `${this.finalUnit}`, '$', `${this.finalUnit}`, '$', `${this.finalUnit}`, '$', '$'];
        let rows: string[][] = [];

        for (const key of rowKeys) {
            const actualUse = this.getValue(key, group.idbGroupId, energyUseTable);
            const actualCost = this.getValue(key, group.idbGroupId, estimatedEnergyCostTable);
            const adjustedUse = this.getValue(key, group.idbGroupId, adjustedEnergyUseTable);
            const adjustedCost = this.getValue(key, group.idbGroupId, expectedEnergyCostTable);
            const energySavings = this.getValue(key, group.idbGroupId, energySavingsTable);
            const avoidedCostSavings = this.getValue(key, group.idbGroupId, costSavingsTable);
            const cumulativeAvoidedCostSavings = this.getValue(key, group.idbGroupId, cumulativeCostSavingsTable);

            rows.push([
                isMonthly ? this.formatMonthLabel(key.toString()) : key.toString(),
                `${this.checkNumber(actualUse, false)}`,
                `${this.checkNumber(actualCost, false)}`,
                `${this.checkNumber(adjustedUse, false)}`,
                `${this.checkNumber(adjustedCost, false)}`,
                `${this.checkNumber(energySavings, false)}`,
                `${this.checkNumber(avoidedCostSavings, false)}`,
                `${this.checkNumber(cumulativeAvoidedCostSavings, false)}`
            ]);
        }

        const tableSection: TableSection = {
            type: 'table',
            title: title,
            headers,
            subHeaders: subheaders,
            rows,
            pageBreakAfter: true,
            tocInclude: true,
            tocLabel: title,
            bookmarkLevel: 1
        };
        return tableSection;
    }

    private createChartSection(chartImageProvider: any, title: string) {
        const chartSection: ChartSection = {
            type: 'chart',
            title: title,
            imageDataProvider: chartImageProvider ? chartImageProvider : undefined,
            pageBreakAfter: true,
            tocInclude: true,
            tocLabel: title,
            bookmarkLevel: 1
        };
        return chartSection;
    }

    checkNumber(value: number, isCurrency: boolean): string {
        if (isNaN(value) || value === null || value === undefined || value === 0) {
            return '\u2014';
        }
        value = Math.round(value);
        return this.customNumberPipe.transform(value, isCurrency);
    }

    checkCostSummaryNumber(value: number): string {
        if (isNaN(value) || value === null || value === undefined || value === 0) {
            return '\u2014';
        }
        value = Math.round((value + Number.EPSILON) * 100) / 100;
        return value.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 });
    }

    formatMonthLabel(monthKey: string) {
        const [year, month] = monthKey.split('-').map(Number);
        const date = new Date(year, month);;
        const formatted = date.toLocaleString('en-US', { month: 'long', year: 'numeric' });
        return formatted.replace(' ', ', ');
    }

    getValue(rowKey: string | number, groupId: string, costSavingsTable: YearGroupData) {
        const key = String(rowKey)
        const value = costSavingsTable[key]?.[groupId];
        return value !== undefined && value !== null && !isNaN(value) ? value : 0;
    }

    getTotal(year: number, costSavingsTable: YearGroupData) {
        let total = 0;
        for (const group of this.filteredGroups) {
            total += this.getValue(year, group.idbGroupId, costSavingsTable);
        }
        return total !== undefined && total !== null && !isNaN(total) ? total : 0;
    }

    getMonthlyTotal(monthKey: string, monthlyCostSavingsTable: MonthlyGroupData) {
        let total = 0;
        for (const group of this.filteredGroups) {
            const value = monthlyCostSavingsTable[monthKey]?.[group.idbGroupId];
            total += value !== undefined && value !== null && !isNaN(value) ? value : 0;
        }
        return total !== undefined && total !== null && !isNaN(total) ? total : 0;
    }
}

export interface FacilityCostSavingsReportData {
    facilityReport: IdbFacilityReport;
    facility: IdbFacility;
    years: Array<number>;
    filteredGroups: Array<AnalysisGroup>;
    costSavingsTable: YearGroupData;
    monthlyCostSavingsTable: MonthlyGroupData;
    monthKeys: Array<string>;
    cumulativeCostSavingsTable: YearGroupData;
    cumulativeMonthlyCostSavingsTable: MonthlyGroupData;
    costDataTable: YearGroupData;
    groupUnits: { [groupId: string]: string };
    convertedCostDataTable: YearGroupData;
    finalUnit: string;
    estimatedEnergyCostTable: YearGroupData;
    expectedEnergyCostTable: YearGroupData;
    energyUseTable: YearGroupData;
    adjustedEnergyUseTable: YearGroupData;
    energySavingsTable: YearGroupData;
    monthlyEnergyUseTable: MonthlyGroupData;
    estimatedMonthlyEnergyCostTable: MonthlyGroupData;
    expectedMonthlyEnergyCostTable: MonthlyGroupData;
    adjustedMonthlyEnergyUseTable: MonthlyGroupData;
    monthlyEnergySavingsTable: MonthlyGroupData;
    chartImageProviders: {
        annualCostSavingsGraph: () => Promise<string>;
        cumulativeAnnualCostSavingsGraph: () => Promise<string>;
        monthlyCostSavingsGraph: () => Promise<string>;
        cumulativeMonthlyCostSavingsGraph: () => Promise<string>;
        groupComparisonGraph: Record<string, () => Promise<string>>;
    };
}