import { inject, Injectable } from "@angular/core";
import { IdbFacilityReport } from "src/app/models/idbModels/facilityReport";
import { MeterDataStats, PredictorDataStats } from "./facility-data-quality-report-results.component";
import { ReportDocument, ReportMetaData } from "src/app/shared/pdf-report/models/report-document.model";
import { BaseSection, ChartSection, HeadingSection, StyledText, StyledTextSection, TableSection } from "src/app/shared/pdf-report/models/report-section.model";
import { getUnitFromMeter } from "src/app/shared/shared-data-quality-report-meters/meterDataQualityStatistics";
import { CustomNumberPipe } from "src/app/shared/helper-pipes/custom-number.pipe";

@Injectable({ providedIn: 'root' })
export class FacilityDataQualityReportAdapter {

    private customNumberPipe: CustomNumberPipe = inject(CustomNumberPipe);
    report: IdbFacilityReport;

    buildDocument(input: DataQualityReportData): ReportDocument {
        const sections: BaseSection[] = [];
        this.report = input.facilityReport;

        let metadata: ReportMetaData = {
            title: `${this.report.name}`,
            subtitle: 'GENERATED BY VERIFI',
            dateGenerated: new Date().toISOString(),
            moduleColor: [46, 81, 127]
        };
        sections.push(...this.buildMeterDataSections(input.meterDataStatsList, input.chartImageProviders));
        sections.push(...this.buildPredictorDataSections(input.predictorDataStatsList, input.chartImageProviders));

        return {
            metadata,
            sections
        };
    }

    private buildMeterDataSections(statsList: MeterDataStats[], chartImageProviders: any): BaseSection[] {
        let sections: BaseSection[] = [];
        if (statsList) {
            statsList.forEach(stats => {
                if (this.report.dataQualityReportSettings.includeMeterStatisticsTable ||
                    this.report.dataQualityReportSettings.includeMeterConsumptionTimeseriesGraph ||
                    this.report.dataQualityReportSettings.includeMeterCostTimeseriesGraph ||
                    this.report.dataQualityReportSettings.includeMeterConsumptionHistogram ||
                    this.report.dataQualityReportSettings.includeMeterCostHistogram
                ) {
                    let meterTitle = stats.meter.name;
                    let titleSection: StyledTextSection = {
                        type: 'styledText',
                        verticalCenter: true,
                        content: [{
                            text: meterTitle,
                            fontSize: 16,
                            bold: true,
                            align: 'center',
                        }],
                        pageBreakAfter: true,
                        tocInclude: true,
                        tocLabel: meterTitle,
                        bookmarkLevel: 0
                    };
                    sections.push(titleSection);
                }

                if (this.report.dataQualityReportSettings.includeMeterStatisticsTable) {
                    let tableSection = this.createMeterTableSection(stats, 'Total Consumption and Cost Statistics');
                    if (tableSection) {
                        tableSection.tocInclude = true;
                        tableSection.tocLabel = 'Total Consumption and Cost Statistics';
                        tableSection.bookmarkLevel = 1;
                        tableSection.pageBreakAfter = true;
                        sections.push(tableSection);
                    }
                }

                if (this.report.dataQualityReportSettings.includeMeterConsumptionTimeseriesGraph) {
                    let chartSection = this.createChartSection(chartImageProviders?.meterConsumptionTimeseries[stats.meter.guid], 'Total Consumption');
                    if (chartSection) {
                        chartSection.tocInclude = true;
                        chartSection.tocLabel = 'Total Consumption Timeseries';
                        chartSection.bookmarkLevel = 1;
                        chartSection.pageBreakAfter = true;
                        sections.push(chartSection);
                    }
                }
                if (stats.includeCosts && this.report.dataQualityReportSettings.includeMeterCostTimeseriesGraph) {
                    let chartSection = this.createChartSection(chartImageProviders?.meterCostTimeseries[stats.meter.guid], 'Total Cost');
                    if (chartSection) {
                        chartSection.tocInclude = true;
                        chartSection.tocLabel = 'Total Cost Timeseries';
                        chartSection.bookmarkLevel = 1;
                        chartSection.pageBreakAfter = true;
                        sections.push(chartSection);
                    }
                }
                if (this.report.dataQualityReportSettings.includeMeterConsumptionHistogram) {
                    let chartSection = this.createChartSection(chartImageProviders?.meterEnergyHistogram[stats.meter.guid], 'Distribution of Total Consumption');
                    if (chartSection) {
                        chartSection.tocInclude = true;
                        chartSection.tocLabel = 'Distribution of Total Consumption';
                        chartSection.bookmarkLevel = 1;
                        chartSection.pageBreakAfter = true;
                        sections.push(chartSection);
                    }
                }
                if (stats.includeCosts && this.report.dataQualityReportSettings.includeMeterCostHistogram) {
                    let chartSection = this.createChartSection(chartImageProviders?.meterCostHistogram[stats.meter.guid], 'Distribution of Total Cost');
                    if (chartSection) {
                        chartSection.tocInclude = true;
                        chartSection.tocLabel = 'Distribution of Total Cost';
                        chartSection.bookmarkLevel = 1;
                        chartSection.pageBreakAfter = true;
                        sections.push(chartSection);
                    }
                }
            });
        }
        return sections;
    }

    private buildPredictorDataSections(statsList: PredictorDataStats[], chartImageProviders: any): BaseSection[] {
        let sections: BaseSection[] = [];
        if (statsList) {
            statsList.forEach(stats => {
                if (this.report.dataQualityReportSettings.includePredictorStatisticsTable ||
                    this.report.dataQualityReportSettings.includePredictorTimeseriesGraph ||
                    this.report.dataQualityReportSettings.includePredictorHistogram) {
                } {
                    let predictorTitle = stats.predictor.name;
                    let titleSection: StyledTextSection = {
                        type: 'styledText',
                        verticalCenter: true,
                        content: [{
                            text: predictorTitle,
                            fontSize: 16,
                            bold: true,
                            align: 'center',
                        }],
                        pageBreakAfter: true,
                        tocInclude: true,
                        tocLabel: predictorTitle,
                        bookmarkLevel: 0
                    };
                    sections.push(titleSection);
                }

                if (this.report.dataQualityReportSettings.includePredictorStatisticsTable) {
                    let tableSection = this.createPredictorTableSection(stats, 'Total Consumption Statistics');
                    if (tableSection) {
                        tableSection.tocInclude = true;
                        tableSection.tocLabel = 'Total Consumption Statistics';
                        tableSection.bookmarkLevel = 1;
                        tableSection.pageBreakAfter = true;
                        sections.push(tableSection);
                    }
                }
                if (this.report.dataQualityReportSettings.includePredictorTimeseriesGraph) {
                    let chartSection = this.createChartSection(chartImageProviders?.predictorTimeseries[stats.predictor.guid], 'Predictor Timeseries');
                    if (chartSection) {
                        chartSection.tocInclude = true;
                        chartSection.tocLabel = 'Predictor Timeseries';
                        chartSection.bookmarkLevel = 1;
                        chartSection.pageBreakAfter = true;
                        sections.push(chartSection);
                    }
                }
                if (this.report.dataQualityReportSettings.includePredictorHistogram) {
                    let chartSection = this.createChartSection(chartImageProviders?.predictorHistogram[stats.predictor.guid], 'Distribution of Predictors');
                    if (chartSection) {
                        chartSection.tocInclude = true;
                        chartSection.tocLabel = 'Distribution of Predictors';
                        chartSection.bookmarkLevel = 1;
                        chartSection.pageBreakAfter = true;
                        sections.push(chartSection);
                    }
                }
            });
        }
        return sections;
    }

    private createMeterTableSection(meterStats: MeterDataStats, title: string) {
        let unit = getUnitFromMeter(meterStats.meter, meterStats.data);
        let headers: Array<string> = ['', 'Minimum', 'Maximum', 'Average', 'Median', 'Median Absolute Deviation (MAD)', `Median - 5 MAD`, `Median + 5 MAD`, 'Number of Outliers'];
        let rows: string[][] = [];

        if (!(meterStats.meter.source == 'Electricity' && !meterStats.meter.includeInEnergy)) {
            rows.push([
                `Total Consumption (${unit})`,
                this.checkNumber(meterStats.energyStats.min),
                this.checkNumber(meterStats.energyStats.max),
                this.checkNumber(meterStats.energyStats.average),
                this.checkNumber(meterStats.energyStats.median),
                this.checkNumber(meterStats.energyStats.medianAbsDev),
                this.checkNumber(meterStats.energyStats.medianminus2_5MAD),
                this.checkNumber(meterStats.energyStats.medianplus2_5MAD),
                this.checkNumber(meterStats.energyOutlierCount)
            ]);

            if (meterStats.includeCosts) {
                rows.push([
                    `Total Cost ($)`,
                    this.checkNumber(meterStats.costStats.min),
                    this.checkNumber(meterStats.costStats.max),
                    this.checkNumber(meterStats.costStats.average),
                    this.checkNumber(meterStats.costStats.median),
                    this.checkNumber(meterStats.costStats.medianAbsDev),
                    this.checkNumber(meterStats.costStats.medianminus2_5MAD),
                    this.checkNumber(meterStats.costStats.medianplus2_5MAD),
                    this.checkNumber(meterStats.costOutlierCount)
                ]);
            }
        }

        const tableSection: TableSection = {
            type: 'table',
            title: title,
            headers: headers,
            rows: rows
        };

        return tableSection;
    }

    private createPredictorTableSection(predictorStats: PredictorDataStats, title: string) {
        let headers: Array<string> = ['', 'Minimum', 'Maximum', 'Average', 'Median', 'Median Absolute Deviation (MAD)', `Median - 5 MAD`, `Median + 5 MAD`, 'Number of Outliers'];
        let rows: string[][] = [];

        let predictorName: string = predictorStats.predictor.name;
        if (predictorStats.predictor.unit && predictorStats.predictor.predictorType != 'Weather') {
            predictorName = `${predictorName} (${predictorStats.predictor.unit})`;
        }
        else if (predictorStats.predictor.predictorType == 'Weather') {
            if (predictorStats.predictor.weatherDataType == 'HDD') {
                predictorName = `${predictorName} (${predictorStats.predictor.weatherDataType}, ${predictorStats.predictor.heatingBaseTemperature}°F)`;
            }
            else if (predictorStats.predictor.weatherDataType == 'CDD') {
                predictorName = `${predictorName} (${predictorStats.predictor.weatherDataType}, ${predictorStats.predictor.coolingBaseTemperature}°F)`;
            }
            else if (predictorStats.predictor.weatherDataType == 'relativeHumidity') {
                predictorName = `${predictorName} (Relative Humidity %)`;
            }
            else if (predictorStats.predictor.weatherDataType == 'dryBulbTemp') {
                predictorName = `${predictorName} (Dry Bulb Temp. °F)`;
            }
        }

        if (predictorStats.data && predictorStats.data.length > 0) {
            rows.push([
                predictorName,
                this.checkNumber(predictorStats.stats.min),
                this.checkNumber(predictorStats.stats.max),
                this.checkNumber(predictorStats.stats.average),
                this.checkNumber(predictorStats.stats.median),
                this.checkNumber(predictorStats.stats.medianAbsDev),
                this.checkNumber(predictorStats.stats.medianminus2_5MAD),
                this.checkNumber(predictorStats.stats.medianplus2_5MAD),
                this.checkNumber(predictorStats.stats.outliers)
            ]);
        }

        const tableSection: TableSection = {
            type: 'table',
            title: title,
            headers: headers,
            rows: rows
        };

        return tableSection;
    }

    private createChartSection(chartImageProvider: any, title: string) {
        const chartSection: ChartSection = {
            type: 'chart',
            title: title,
            imageDataProvider: chartImageProvider ? chartImageProvider : undefined
        };
        return chartSection;
    }

    checkNumber(value: number): string {
        if (isNaN(value) || value === null || value === undefined) {
            return '-';
        }
        return this.customNumberPipe.transform(value);
    }
}

export interface DataQualityReportData {
    facilityReport: IdbFacilityReport;
    meterDataStatsList: Array<MeterDataStats>;
    predictorDataStatsList: Array<PredictorDataStats>;
    chartImageProviders?: {
        meterConsumptionTimeseries?: Record<string, () => Promise<string>>;
        meterCostTimeseries?: Record<string, () => Promise<string>>;
        meterConsumptionHistogram?: Record<string, () => Promise<string>>;
        meterCostHistogram?: Record<string, () => Promise<string>>;
        predictorTimeseries?: Record<string, () => Promise<string>>;
        predictorHistogram?: Record<string, () => Promise<string>>;
    }
}