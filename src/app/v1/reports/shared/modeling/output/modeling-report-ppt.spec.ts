import { buildModelingReport } from '@domain/reports/modeling-report';
import { modelingRegressionCells, modelingValidationRows } from '../modeling-report-tables';
import { modelingExportFixture } from '../testing/modeling-report-export-fixture';
import { modelingPptDocument } from './modeling-report-ppt';

describe('Modeling PowerPoint composition', () => {
  it('keeps earlier-cutoff chart slides free of an extra note', () => {
    const snapshot = modelingExportFixture(), normal = modelingPptDocument(snapshot);
    const deck = modelingPptDocument({ ...snapshot, view: { ...snapshot.view, reportYear: 2024 } });
    expect(deck.slides).toHaveLength(normal.slides.length);
    expect(deck.slides.find(slide => slide.type === 'image')?.note).toBeUndefined();
  });
  it('retains repeated facility/group identities for account-scoped details', () => {
    const snapshot = modelingExportFixture();
    const deck = modelingPptDocument({ ...snapshot, view: { ...snapshot.view, scope: 'account' } });
    const details = deck.slides.find(slide => slide.type === 'table' && slide.equation);
    expect(details?.title).toBe('Plant A · Main meters');
    expect(details?.type === 'table' && details.headers[0]).toBe('Facility / Group');
  });
  it.each(Array.from({ length: 8 }, (_, mask) => mask))('includes exactly the selected section dividers (mask %i)', mask => {
    const snapshot = modelingExportFixture(), original = structuredClone(snapshot);
    const settings = { includeIssuesSummary: !!(mask & 1), includeExecutiveSummary: !!(mask & 2), includeDataValidationTables: !!(mask & 4) };
    const deck = modelingPptDocument({ ...snapshot, view: { ...snapshot.view, settings } });
    expect(deck.slides.filter(slide => slide.type === 'title' && slide.layout === 'section').map(slide => slide.title)).toEqual([
      ...(settings.includeIssuesSummary ? ['Issues Summary'] : []),
      ...(settings.includeExecutiveSummary ? ['Executive Summary'] : []),
      ...(settings.includeDataValidationTables ? ['Model Details'] : [])
    ]);
    expect(deck.slides[0]).toMatchObject({ type: 'title', title: snapshot.name, subtitle: 'Plant A\nGenerated by VERIFI' });
    expect(snapshot).toEqual(original);
    if (!mask) expect(deck.slides).toHaveLength(1);
  });

  it.each([true, false])('shares model values and preserves the repeated facility/group identifier (user defined: %s)', userDefined => {
    const snapshot = modelingExportFixture(), group = snapshot.view.regression[0];
    Object.assign(group.model!, { isUserDefinedModel: userDefined, R2: 0, adjust_R2: 0, modelPValue: 0 });
    group.groupName = 'CO₂ manufacturing';
    const deck = modelingPptDocument(snapshot), cells = modelingRegressionCells(group);
    const regression = deck.slides.find(slide => slide.type === 'table' && slide.title === 'Analysis Type: Regression');
    expect(regression?.type === 'table' && regression.rows[0]).toEqual([`${cells[0]} · ${cells[1]}`, ...cells.slice(2)]);
    if (!userDefined) expect(regression?.type === 'table' && regression.rows[0].slice(3, 6)).toEqual(['0.000', '0.000', '0.00']);
    const tables = deck.slides.filter(slide => slide.type === 'table' && slide.title === 'CO₂ manufacturing');
    expect(tables).toHaveLength(2);
    expect(tables[0].type === 'table' && tables[0].headers[0]).toBe('Model period');
    expect(tables[0].type === 'table' && tables[0].headers).toHaveLength(6);
    expect(tables[0].type === 'table' && tables[0].rows[0][0]).toContain(userDefined ? 'User defined' : '2022');
    expect(tables[0].type === 'table' && tables[0].headers).not.toContain('Formula');
    expect(tables[0].type === 'table' && tables[0].equation?.expression).toBe(cells[7]);
    expect(deck.slides[deck.slides.indexOf(tables[0]) + 1].type).toBe('image');
    expect(tables[1].type === 'table' && tables[1].rows).toEqual(modelingValidationRows(group));
    expect(deck.slides.some(slide => ['Regression model statistics', 'Predictor validation'].includes(slide.title))).toBe(false);
  });

  it('exports diagnostic issues and missing models as editable tables and notes', () => {
    const snapshot = modelingExportFixture(), item = snapshot.view.groups[0];
    const view = buildModelingReport({ reportYear: 2023, hasBlockingErrors: true, groups: [{ ...item, model: undefined,
      critical: ['Select a model.'], moderate: ['Outside model range.'], minor: ['Check period.'] }] }, snapshot.view.settings,
      { facilities: {}, groups: { group: 'Main meters' } });
    const deck = modelingPptDocument({ ...snapshot, view });
    const tables = deck.slides.filter(slide => slide.type === 'table');
    for (const severity of ['Critical', 'Moderate', 'Minor']) expect(tables.some(table => table.title === `${severity} issues`)).toBe(true);
    const note = tables.find(table => table.type === 'table' && table.headers[0] === 'Report note' && String(table.rows[0][0]).startsWith('Predictor validation'));
    expect(note?.type === 'table' && note.rows).toEqual([['Predictor validation is unavailable for this model.\nReview the analysis setup.']]);
    expect(JSON.stringify(deck)).toContain('Model unavailable');
  });

  it('includes every supported summary method and renders clean and empty explanations as report notes', () => {
    const snapshot = modelingExportFixture(), item = snapshot.view.groups[0];
    const view = buildModelingReport({ reportYear: 2023, hasBlockingErrors: false,
      groups: (['energyIntensity', 'modifiedEnergyIntensity', 'absoluteEnergyConsumption'] as const).map(analysisType => ({ ...item,
        group: { ...item.group, analysisType }, critical: [], moderate: [], minor: [] })) }, snapshot.view.settings,
      { facilities: {}, groups: {} });
    const deck = modelingPptDocument({ ...snapshot, view });
    for (const method of ['Classic Intensity', 'Modified Intensity', 'Absolute Consumption']) {
      expect(deck.slides.some(slide => slide.type === 'table' && slide.title === `Analysis Type: ${method}`)).toBe(true);
    }
    expect(JSON.stringify(deck)).toContain('No issues identified.');
    expect(JSON.stringify(deck)).toContain('No regression groups are included.');
    const empty = buildModelingReport({ reportYear: 2023, groups: [], hasBlockingErrors: false }, view.settings, { facilities: {}, groups: {} });
    const notes = modelingPptDocument({ ...snapshot, view: empty }).slides.filter(slide => slide.type === 'table');
    expect(notes).toHaveLength(3);
    expect(notes.every(slide => slide.type === 'table' && slide.headers[0] === 'Report note')).toBe(true);
  });
});
